-- V015 · Módulos: perfil nutricional con objetivo calórico (Comida) y registros de trabajo (Trabajo).
-- Datos de salud (peso, altura…) y notas privadas: borrar APP_USERS los elimina en cascada (RGPD: supresión).
CREATE TABLE NUTRITION_GOALS (
    USER_ID           BYTEA           NOT NULL,
    SEX               VARCHAR(1)  NOT NULL,
    AGE_YEARS         INTEGER         NOT NULL,
    HEIGHT_CM         NUMERIC(5,1)       NOT NULL,
    WEIGHT_KG         NUMERIC(5,1)       NOT NULL,
    TARGET_WEIGHT_KG  NUMERIC(5,1)       NOT NULL,
    DAILY_ACTIVITY    VARCHAR(10) NOT NULL,
    JOB_TYPE          VARCHAR(10) NOT NULL,
    SPORT_HOURS_WEEK  NUMERIC(4,1)       NOT NULL,
    GOAL_MODE         VARCHAR(10) NOT NULL,
    UPDATED_AT        TIMESTAMPTZ(6) DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT PK_NUTRITION_GOALS PRIMARY KEY (USER_ID),
    CONSTRAINT FK_NUTRITION_GOALS_USER FOREIGN KEY (USER_ID) REFERENCES APP_USERS (ID) ON DELETE CASCADE,
    CONSTRAINT CK_NUTRITION_GOALS_SEX CHECK (SEX IN ('F','M')),
    CONSTRAINT CK_NUTRITION_GOALS_AGE CHECK (AGE_YEARS BETWEEN 18 AND 100),
    CONSTRAINT CK_NUTRITION_GOALS_HEIGHT CHECK (HEIGHT_CM BETWEEN 120 AND 230),
    CONSTRAINT CK_NUTRITION_GOALS_WEIGHT CHECK (WEIGHT_KG BETWEEN 30 AND 300),
    CONSTRAINT CK_NUTRITION_GOALS_TARGET CHECK (TARGET_WEIGHT_KG BETWEEN 30 AND 300),
    CONSTRAINT CK_NUTRITION_GOALS_ACTIVITY CHECK (DAILY_ACTIVITY IN ('LOW','MODERATE','HIGH')),
    CONSTRAINT CK_NUTRITION_GOALS_JOB CHECK (JOB_TYPE IN ('DESK','ON_FEET','PHYSICAL')),
    CONSTRAINT CK_NUTRITION_GOALS_SPORT CHECK (SPORT_HOURS_WEEK BETWEEN 0 AND 40),
    CONSTRAINT CK_NUTRITION_GOALS_MODE CHECK (GOAL_MODE IN ('MAINTAIN','DEFICIT'))
);
COMMENT ON TABLE NUTRITION_GOALS IS 'Perfil nutricional de la persona (módulo Comida) para estimar su objetivo calórico orientativo. La estimación se calcula al consultarla, no se guarda.';

CREATE TABLE WORK_ENTRIES (
    ID          BYTEA DEFAULT decode(replace(gen_random_uuid()::text, '-', ''), 'hex') NOT NULL,
    USER_ID     BYTEA            NOT NULL,
    ENTRY_DATE  DATE               NOT NULL,
    KIND        VARCHAR(10)  NOT NULL,
    TITLE       VARCHAR(200),
    BODY        TEXT               NOT NULL,
    CREATED_AT  TIMESTAMPTZ(6) DEFAULT CURRENT_TIMESTAMP NOT NULL,
    UPDATED_AT  TIMESTAMPTZ(6) DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT PK_WORK_ENTRIES PRIMARY KEY (ID),
    CONSTRAINT FK_WORK_ENTRIES_USER FOREIGN KEY (USER_ID) REFERENCES APP_USERS (ID) ON DELETE CASCADE,
    CONSTRAINT CK_WORK_ENTRIES_KIND CHECK (KIND IN ('NOTE','SUMMARY','PROMPT'))
);
CREATE INDEX IX_WORK_ENTRIES_USER_DATE ON WORK_ENTRIES (USER_ID, ENTRY_DATE);
COMMENT ON TABLE WORK_ENTRIES IS 'Registros del módulo Trabajo: notas, resúmenes y textos/prompts pegados, por fecha. Texto privado de la persona.';
