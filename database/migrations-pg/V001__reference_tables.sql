-- Alérgenos de declaración obligatoria (Reglamento (UE) 1169/2011, anexo II).
CREATE TABLE ALLERGENS (
    CODE             VARCHAR(30)  NOT NULL,
    EU_ANNEX_NUMBER  INTEGER          NOT NULL,
    NAME_ES          VARCHAR(120) NOT NULL,
    CONSTRAINT PK_ALLERGENS PRIMARY KEY (CODE),
    CONSTRAINT UK_ALLERGENS_ANNEX UNIQUE (EU_ANNEX_NUMBER)
);
COMMENT ON TABLE ALLERGENS IS 'Catálogo de los 14 alérgenos del anexo II del Reglamento (UE) 1169/2011.';

-- Unidades de cantidad: masa, volumen y medidas caseras.
CREATE TABLE PORTION_UNITS (
    CODE          VARCHAR(20) NOT NULL,
    MEASURE_KIND  VARCHAR(10) NOT NULL,
    BASE_FACTOR   NUMERIC(12,6),
    SORT_ORDER    INTEGER DEFAULT 0 NOT NULL,
    CONSTRAINT PK_PORTION_UNITS PRIMARY KEY (CODE),
    CONSTRAINT CK_PORTION_UNITS_KIND CHECK (MEASURE_KIND IN ('MASS','VOLUME','HOUSEHOLD')),
    CONSTRAINT CK_PORTION_UNITS_FACTOR CHECK (
        (MEASURE_KIND IN ('MASS','VOLUME') AND BASE_FACTOR > 0)
        OR (MEASURE_KIND = 'HOUSEHOLD' AND BASE_FACTOR IS NULL))
);
COMMENT ON TABLE PORTION_UNITS IS 'Unidades. MASS y VOLUME convierten con BASE_FACTOR (a g o ml); HOUSEHOLD (vaso, cucharada...) se convierte por alimento en FOOD_PORTIONS.';
COMMENT ON COLUMN PORTION_UNITS.BASE_FACTOR IS 'Factor a la unidad base: g para MASS, ml para VOLUME. Nulo en medidas caseras.';

CREATE TABLE PORTION_UNIT_NAMES (
    UNIT_CODE   VARCHAR(20)  NOT NULL,
    LOCALE      VARCHAR(10)  NOT NULL,
    SINGULAR    VARCHAR(60)  NOT NULL,
    PLURAL      VARCHAR(60)  NOT NULL,
    CONSTRAINT PK_PORTION_UNIT_NAMES PRIMARY KEY (UNIT_CODE, LOCALE),
    CONSTRAINT FK_PORTION_UNIT_NAMES_UNIT FOREIGN KEY (UNIT_CODE) REFERENCES PORTION_UNITS (CODE)
);
COMMENT ON TABLE PORTION_UNIT_NAMES IS 'Nombres localizados de las unidades (es-ES, es-MX...). FK cubierta por la PK.';

-- Secciones del supermercado para agrupar la lista de la compra.
CREATE TABLE SHOPPING_SECTIONS (
    CODE           VARCHAR(30)  NOT NULL,
    DEFAULT_ORDER  INTEGER          NOT NULL,
    NAME_ES        VARCHAR(80)  NOT NULL,
    CONSTRAINT PK_SHOPPING_SECTIONS PRIMARY KEY (CODE)
);
COMMENT ON TABLE SHOPPING_SECTIONS IS 'Secciones de tienda (frutería, lácteos...). El orden personal por tienda está en HOUSEHOLD_STORE_LAYOUTS.';

-- Categorías jerárquicas de alimentos.
CREATE TABLE FOOD_CATEGORIES (
    ID                  BIGINT GENERATED BY DEFAULT AS IDENTITY,
    CODE                VARCHAR(40)  NOT NULL,
    PARENT_ID           BIGINT,
    NAME_ES             VARCHAR(120) NOT NULL,
    SHOPPING_SECTION    VARCHAR(30),
    SUBSTITUTION_ROLE   VARCHAR(30),
    SORT_ORDER          INTEGER DEFAULT 0 NOT NULL,
    CONSTRAINT PK_FOOD_CATEGORIES PRIMARY KEY (ID),
    CONSTRAINT UK_FOOD_CATEGORIES_CODE UNIQUE (CODE),
    CONSTRAINT FK_FOOD_CATEGORIES_PARENT FOREIGN KEY (PARENT_ID) REFERENCES FOOD_CATEGORIES (ID),
    CONSTRAINT FK_FOOD_CATEGORIES_SECTION FOREIGN KEY (SHOPPING_SECTION) REFERENCES SHOPPING_SECTIONS (CODE),
    CONSTRAINT CK_FOOD_CATEGORIES_ROLE CHECK (SUBSTITUTION_ROLE IS NULL OR SUBSTITUTION_ROLE IN
        ('STARCH','PROTEIN','VEGETABLE','FRUIT','DAIRY','FAT','LEGUME','SWEET','BEVERAGE','CONDIMENT','DISH'))
);
CREATE INDEX IX_FOOD_CATEGORIES_PARENT ON FOOD_CATEGORIES (PARENT_ID);
CREATE INDEX IX_FOOD_CATEGORIES_SECTION ON FOOD_CATEGORIES (SHOPPING_SECTION);
COMMENT ON TABLE FOOD_CATEGORIES IS 'Árbol de categorías del catálogo.';
COMMENT ON COLUMN FOOD_CATEGORIES.SUBSTITUTION_ROLE IS 'Papel culinario usado por el motor de sustituciones (p. ej. STARCH: arroz, patata, pasta).';

-- Definición de nutrientes adicionales (micronutrientes) más allá de las columnas fijas.
CREATE TABLE NUTRIENT_DEFINITIONS (
    CODE        VARCHAR(30)  NOT NULL,
    UNIT        VARCHAR(10)  NOT NULL,
    NAME_ES     VARCHAR(120) NOT NULL,
    INFOODS_TAG VARCHAR(30),
    SORT_ORDER  INTEGER DEFAULT 0 NOT NULL,
    CONSTRAINT PK_NUTRIENT_DEFINITIONS PRIMARY KEY (CODE),
    CONSTRAINT CK_NUTRIENT_DEFINITIONS_UNIT CHECK (UNIT IN ('g','mg','ug','kcal','kJ'))
);
COMMENT ON TABLE NUTRIENT_DEFINITIONS IS 'Nutrientes opcionales (calcio, hierro, vitamina D...) guardados en PROFILE_NUTRIENTS. INFOODS_TAG facilita el cruce con fuentes.';

-- Fuentes de datos y sus licencias (procedencia obligatoria de todo dato del catálogo).
CREATE TABLE DATA_SOURCES (
    ID                      BIGINT GENERATED BY DEFAULT AS IDENTITY,
    CODE                    VARCHAR(30)   NOT NULL,
    NAME                    VARCHAR(200)  NOT NULL,
    SOURCE_KIND             VARCHAR(20)   NOT NULL,
    LICENSE_CODE            VARCHAR(60),
    LICENSE_URL             VARCHAR(500),
    ATTRIBUTION_TEXT        VARCHAR(1000),
    SHARE_ALIKE             BOOLEAN DEFAULT FALSE NOT NULL,
    COMMERCIAL_USE          VARCHAR(10)   DEFAULT 'UNKNOWN' NOT NULL,
    RELIABILITY_WEIGHT      NUMERIC(3,2)         DEFAULT 1 NOT NULL,
    IS_ACTIVE               BOOLEAN DEFAULT TRUE NOT NULL,
    CONSTRAINT PK_DATA_SOURCES PRIMARY KEY (ID),
    CONSTRAINT UK_DATA_SOURCES_CODE UNIQUE (CODE),
    CONSTRAINT CK_DATA_SOURCES_KIND CHECK (SOURCE_KIND IN
        ('COMPOSITION_DB','PRODUCT_DB','LABEL','LITERATURE','SAFETY_GUIDE','USER','ADMIN','PRICE_FEED')),
    CONSTRAINT CK_DATA_SOURCES_COMMERCIAL CHECK (COMMERCIAL_USE IN ('YES','NO','UNKNOWN')),
    CONSTRAINT CK_DATA_SOURCES_WEIGHT CHECK (RELIABILITY_WEIGHT BETWEEN 0 AND 1)
);
COMMENT ON TABLE DATA_SOURCES IS 'Origen de los datos (BEDCA, CIQUAL, Open Food Facts, etiqueta, usuario...). Ninguna fuente con COMMERCIAL_USE=NO puede publicarse en el catálogo comercial.';
COMMENT ON COLUMN DATA_SOURCES.RELIABILITY_WEIGHT IS 'Peso en la mediana ponderada del motor de agrupación (laboratorio > etiqueta > usuario).';

-- Tipos de actividad física.
CREATE TABLE ACTIVITY_TYPES (
    CODE          VARCHAR(30)  NOT NULL,
    NAME_ES       VARCHAR(80)  NOT NULL,
    HAS_DISTANCE  BOOLEAN DEFAULT FALSE NOT NULL,
    HAS_STEPS     BOOLEAN DEFAULT FALSE NOT NULL,
    SORT_ORDER    INTEGER DEFAULT 0 NOT NULL,
    CONSTRAINT PK_ACTIVITY_TYPES PRIMARY KEY (CODE)
);
COMMENT ON TABLE ACTIVITY_TYPES IS 'Tipos de actividad (caminar, correr, bici, gimnasio, baile...).';

-- Etiquetas de recetas (5 ingredientes, una sartén, airfryer, táper...).
CREATE TABLE TAG_DEFINITIONS (
    CODE      VARCHAR(40) NOT NULL,
    TAG_KIND  VARCHAR(20) NOT NULL,
    NAME_ES   VARCHAR(80) NOT NULL,
    CONSTRAINT PK_TAG_DEFINITIONS PRIMARY KEY (CODE),
    CONSTRAINT CK_TAG_DEFINITIONS_KIND CHECK (TAG_KIND IN ('METHOD','APPLIANCE','TIME','BUDGET','DIET','OCCASION','FLAVOUR','NUTRITION'))
);
COMMENT ON TABLE TAG_DEFINITIONS IS 'Vocabulario controlado de etiquetas de recetas para filtros y para el asistente.';

-- Cadenas de supermercado (datos públicos de referencia; no implica acuerdo con ellas).
CREATE TABLE STORES (
    ID            BIGINT GENERATED BY DEFAULT AS IDENTITY,
    CHAIN_NAME    VARCHAR(120) NOT NULL,
    COUNTRY_CODE  VARCHAR(2)   NOT NULL,
    IS_ACTIVE     BOOLEAN DEFAULT TRUE NOT NULL,
    CONSTRAINT PK_STORES PRIMARY KEY (ID),
    CONSTRAINT UK_STORES_CHAIN UNIQUE (CHAIN_NAME, COUNTRY_CODE)
);
COMMENT ON TABLE STORES IS 'Cadenas de supermercado de referencia para listas y precios.';
