CREATE TABLE PREPARED_BATCHES (
    ID                  BYTEA DEFAULT decode(replace(gen_random_uuid()::text, '-', ''), 'hex') NOT NULL,
    HOUSEHOLD_ID        BYTEA            NOT NULL,
    RECIPE_VERSION_ID   BYTEA,
    NAME                VARCHAR(200) NOT NULL,
    PREPARED_ON         DATE               NOT NULL,
    SERVINGS_TOTAL      NUMERIC(6,2)        NOT NULL,
    SERVINGS_REMAINING  NUMERIC(6,2)        NOT NULL,
    STORAGE_LOCATION    VARCHAR(10)  DEFAULT 'FRIDGE' NOT NULL,
    CONSUME_BY_DATE     DATE,
    CONSUME_BY_ORIGIN   VARCHAR(10)  DEFAULT 'NONE' NOT NULL,
    CONSUME_BY_SOURCE_ID BIGINT,
    ROW_VERSION         BIGINT DEFAULT 0 NOT NULL,
    CREATED_AT          TIMESTAMPTZ(6) DEFAULT CURRENT_TIMESTAMP NOT NULL,
    UPDATED_AT          TIMESTAMPTZ(6) DEFAULT CURRENT_TIMESTAMP NOT NULL,
    DELETED_AT          TIMESTAMPTZ(6),
    SYNC_SEQ            BIGINT NOT NULL,
    CONSTRAINT PK_PREPARED_BATCHES PRIMARY KEY (ID),
    CONSTRAINT FK_PREPARED_BATCHES_HOUSEHOLD FOREIGN KEY (HOUSEHOLD_ID) REFERENCES HOUSEHOLDS (ID) ON DELETE CASCADE,
    CONSTRAINT FK_PREPARED_BATCHES_RECIPE FOREIGN KEY (RECIPE_VERSION_ID) REFERENCES RECIPE_VERSIONS (ID) ON DELETE SET NULL,
    CONSTRAINT FK_PREPARED_BATCHES_SOURCE FOREIGN KEY (CONSUME_BY_SOURCE_ID) REFERENCES DATA_SOURCES (ID),
    CONSTRAINT CK_PREPARED_BATCHES_SERVINGS CHECK (SERVINGS_TOTAL > 0 AND SERVINGS_REMAINING BETWEEN 0 AND SERVINGS_TOTAL),
    CONSTRAINT CK_PREPARED_BATCHES_LOCATION CHECK (STORAGE_LOCATION IN ('FRIDGE','FREEZER','PANTRY')),
    CONSTRAINT CK_PREPARED_BATCHES_ORIGIN CHECK (
        (CONSUME_BY_ORIGIN = 'NONE' AND CONSUME_BY_DATE IS NULL)
        OR (CONSUME_BY_ORIGIN = 'USER' AND CONSUME_BY_DATE IS NOT NULL)
        OR (CONSUME_BY_ORIGIN = 'GUIDANCE' AND CONSUME_BY_DATE IS NOT NULL AND CONSUME_BY_SOURCE_ID IS NOT NULL))
);
CREATE INDEX IX_PREPARED_BATCHES_HOUSEHOLD ON PREPARED_BATCHES (HOUSEHOLD_ID, SYNC_SEQ);
CREATE INDEX IX_PREPARED_BATCHES_RECIPE ON PREPARED_BATCHES (RECIPE_VERSION_ID);
CREATE INDEX IX_PREPARED_BATCHES_SOURCE ON PREPARED_BATCHES (CONSUME_BY_SOURCE_ID);
COMMENT ON TABLE PREPARED_BATCHES IS 'Cocina por lotes y sobras: raciones preparadas que se reparten en distintos días. La fecha límite solo la pone la persona o una guía de seguridad identificada; nunca se deduce.';

CREATE TABLE PANTRY_ITEMS (
    ID                  BYTEA DEFAULT decode(replace(gen_random_uuid()::text, '-', ''), 'hex') NOT NULL,
    HOUSEHOLD_ID        BYTEA           NOT NULL,
    FOOD_ID             BIGINT,
    PRODUCT_ID          BIGINT,
    FREE_TEXT           VARCHAR(150),
    STOCK_STATUS        VARCHAR(10) DEFAULT 'AVAILABLE' NOT NULL,
    QUANTITY            NUMERIC(10,3),
    UNIT_CODE           VARCHAR(20),
    STORAGE_LOCATION    VARCHAR(10) DEFAULT 'PANTRY' NOT NULL,
    USE_BY_DATE         DATE,
    BEST_BEFORE_DATE    DATE,
    OPENED_ON           DATE,
    IS_STAPLE           BOOLEAN DEFAULT FALSE NOT NULL,
    PREPARED_BATCH_ID   BYTEA,
    ROW_VERSION         BIGINT DEFAULT 0 NOT NULL,
    CREATED_AT          TIMESTAMPTZ(6) DEFAULT CURRENT_TIMESTAMP NOT NULL,
    UPDATED_AT          TIMESTAMPTZ(6) DEFAULT CURRENT_TIMESTAMP NOT NULL,
    DELETED_AT          TIMESTAMPTZ(6),
    SYNC_SEQ            BIGINT NOT NULL,
    CONSTRAINT PK_PANTRY_ITEMS PRIMARY KEY (ID),
    CONSTRAINT FK_PANTRY_ITEMS_HOUSEHOLD FOREIGN KEY (HOUSEHOLD_ID) REFERENCES HOUSEHOLDS (ID) ON DELETE CASCADE,
    CONSTRAINT FK_PANTRY_ITEMS_FOOD FOREIGN KEY (FOOD_ID) REFERENCES FOODS (ID) ON DELETE SET NULL,
    CONSTRAINT FK_PANTRY_ITEMS_PRODUCT FOREIGN KEY (PRODUCT_ID) REFERENCES COMMERCIAL_PRODUCTS (ID) ON DELETE SET NULL,
    CONSTRAINT FK_PANTRY_ITEMS_UNIT FOREIGN KEY (UNIT_CODE) REFERENCES PORTION_UNITS (CODE),
    CONSTRAINT FK_PANTRY_ITEMS_BATCH FOREIGN KEY (PREPARED_BATCH_ID) REFERENCES PREPARED_BATCHES (ID) ON DELETE CASCADE,
    CONSTRAINT CK_PANTRY_ITEMS_REFERENCE CHECK (FOOD_ID IS NOT NULL OR PRODUCT_ID IS NOT NULL OR FREE_TEXT IS NOT NULL OR PREPARED_BATCH_ID IS NOT NULL),
    CONSTRAINT CK_PANTRY_ITEMS_STATUS CHECK (STOCK_STATUS IN ('AVAILABLE','LOW','OUT')),
    CONSTRAINT CK_PANTRY_ITEMS_LOCATION CHECK (STORAGE_LOCATION IN ('FRIDGE','FREEZER','PANTRY','OTHER')),
    CONSTRAINT CK_PANTRY_ITEMS_QUANTITY CHECK (QUANTITY IS NULL OR (QUANTITY >= 0 AND UNIT_CODE IS NOT NULL))
);
CREATE INDEX IX_PANTRY_ITEMS_HOUSEHOLD ON PANTRY_ITEMS (HOUSEHOLD_ID, SYNC_SEQ);
CREATE INDEX IX_PANTRY_ITEMS_FOOD ON PANTRY_ITEMS (FOOD_ID);
CREATE INDEX IX_PANTRY_ITEMS_PRODUCT ON PANTRY_ITEMS (PRODUCT_ID);
CREATE INDEX IX_PANTRY_ITEMS_UNIT ON PANTRY_ITEMS (UNIT_CODE);
CREATE INDEX IX_PANTRY_ITEMS_BATCH ON PANTRY_ITEMS (PREPARED_BATCH_ID);
COMMENT ON TABLE PANTRY_ITEMS IS 'Despensa en dos niveles: sencillo (solo STOCK_STATUS) o avanzado (cantidad, ubicación, fechas). Sin cantidades sigue siendo útil.';
COMMENT ON COLUMN PANTRY_ITEMS.USE_BY_DATE IS 'Fecha de caducidad introducida por la persona (etiqueta). Nunca inferida.';
COMMENT ON COLUMN PANTRY_ITEMS.BEST_BEFORE_DATE IS 'Fecha de consumo preferente introducida por la persona (etiqueta). Nunca inferida.';

