-- Módulo de precios, independiente del catálogo nutricional.
CREATE TABLE PRICE_OBSERVATIONS (
    ID                  BYTEA DEFAULT decode(replace(gen_random_uuid()::text, '-', ''), 'hex') NOT NULL,
    FOOD_ID             BIGINT,
    PRODUCT_ID          BIGINT,
    STORE_ID            BIGINT,
    PRICE_AMOUNT        NUMERIC(10,2)      NOT NULL,
    CURRENCY_CODE       VARCHAR(3)  DEFAULT 'EUR' NOT NULL,
    PACK_QUANTITY       NUMERIC(10,3)      NOT NULL,
    PACK_UNIT_CODE      VARCHAR(20) NOT NULL,
    PRICE_KIND          VARCHAR(10) NOT NULL,
    OBSERVED_ON         DATE              NOT NULL,
    SOURCE_ID           BIGINT,
    OWNER_USER_ID       BYTEA,
    SHARED_WITH_COMMUNITY BOOLEAN DEFAULT FALSE NOT NULL,
    CREATED_AT          TIMESTAMPTZ(6) DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT PK_PRICE_OBSERVATIONS PRIMARY KEY (ID),
    CONSTRAINT FK_PRICE_OBS_FOOD FOREIGN KEY (FOOD_ID) REFERENCES FOODS (ID) ON DELETE CASCADE,
    CONSTRAINT FK_PRICE_OBS_PRODUCT FOREIGN KEY (PRODUCT_ID) REFERENCES COMMERCIAL_PRODUCTS (ID) ON DELETE CASCADE,
    CONSTRAINT FK_PRICE_OBS_STORE FOREIGN KEY (STORE_ID) REFERENCES STORES (ID),
    CONSTRAINT FK_PRICE_OBS_UNIT FOREIGN KEY (PACK_UNIT_CODE) REFERENCES PORTION_UNITS (CODE),
    CONSTRAINT FK_PRICE_OBS_SOURCE FOREIGN KEY (SOURCE_ID) REFERENCES DATA_SOURCES (ID),
    CONSTRAINT FK_PRICE_OBS_OWNER FOREIGN KEY (OWNER_USER_ID) REFERENCES APP_USERS (ID) ON DELETE CASCADE,
    CONSTRAINT CK_PRICE_OBS_TARGET CHECK (
        (FOOD_ID IS NULL AND PRODUCT_ID IS NOT NULL) OR (FOOD_ID IS NOT NULL AND PRODUCT_ID IS NULL)),
    CONSTRAINT CK_PRICE_OBS_AMOUNT CHECK (PRICE_AMOUNT >= 0 AND PACK_QUANTITY > 0),
    CONSTRAINT CK_PRICE_OBS_KIND CHECK (PRICE_KIND IN ('VERIFIED','IMPORTED','RECEIPT','MANUAL','ESTIMATE')),
    CONSTRAINT CK_PRICE_OBS_PRIVATE CHECK (PRICE_KIND NOT IN ('RECEIPT','MANUAL') OR OWNER_USER_ID IS NOT NULL),
    CONSTRAINT CK_PRICE_OBS_EXTERNAL CHECK (PRICE_KIND NOT IN ('VERIFIED','IMPORTED') OR SOURCE_ID IS NOT NULL)
);
CREATE INDEX IX_PRICE_OBS_FOOD ON PRICE_OBSERVATIONS (FOOD_ID, STORE_ID, OBSERVED_ON);
CREATE INDEX IX_PRICE_OBS_PRODUCT ON PRICE_OBSERVATIONS (PRODUCT_ID, OBSERVED_ON);
CREATE INDEX IX_PRICE_OBS_STORE ON PRICE_OBSERVATIONS (STORE_ID);
CREATE INDEX IX_PRICE_OBS_UNIT ON PRICE_OBSERVATIONS (PACK_UNIT_CODE);
CREATE INDEX IX_PRICE_OBS_SOURCE ON PRICE_OBSERVATIONS (SOURCE_ID);
CREATE INDEX IX_PRICE_OBS_OWNER ON PRICE_OBSERVATIONS (OWNER_USER_ID);
COMMENT ON TABLE PRICE_OBSERVATIONS IS 'Precios con tipo explícito: VERIFIED/IMPORTED (fuente autorizada), RECEIPT (ticket), MANUAL, ESTIMATE. Los precios de una persona son privados salvo consentimiento para compartirlos.';

-- Enlaces de solo lectura/marcado para compartir sin cuenta (p. ej. la lista por WhatsApp).
CREATE TABLE SHARE_LINKS (
    ID                  BYTEA DEFAULT decode(replace(gen_random_uuid()::text, '-', ''), 'hex') NOT NULL,
    HOUSEHOLD_ID        BYTEA            NOT NULL,
    RESOURCE_KIND       VARCHAR(20)  NOT NULL,
    RESOURCE_ID         BYTEA            NOT NULL,
    TOKEN_HASH          VARCHAR(128) NOT NULL,
    PERMISSION          VARCHAR(12)  DEFAULT 'READ' NOT NULL,
    CREATED_BY_USER_ID  BYTEA            NOT NULL,
    EXPIRES_AT          TIMESTAMPTZ(6) NOT NULL,
    REVOKED_AT          TIMESTAMPTZ(6),
    CREATED_AT          TIMESTAMPTZ(6) DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT PK_SHARE_LINKS PRIMARY KEY (ID),
    CONSTRAINT UK_SHARE_LINKS_TOKEN UNIQUE (TOKEN_HASH),
    CONSTRAINT FK_SHARE_LINKS_HOUSEHOLD FOREIGN KEY (HOUSEHOLD_ID) REFERENCES HOUSEHOLDS (ID) ON DELETE CASCADE,
    CONSTRAINT FK_SHARE_LINKS_CREATOR FOREIGN KEY (CREATED_BY_USER_ID) REFERENCES APP_USERS (ID) ON DELETE CASCADE,
    CONSTRAINT CK_SHARE_LINKS_KIND CHECK (RESOURCE_KIND IN ('SHOPPING_LIST','MEAL_PLAN','RECIPE')),
    CONSTRAINT CK_SHARE_LINKS_PERMISSION CHECK (PERMISSION IN ('READ','CHECK_ITEMS'))
);
CREATE INDEX IX_SHARE_LINKS_HOUSEHOLD ON SHARE_LINKS (HOUSEHOLD_ID);
CREATE INDEX IX_SHARE_LINKS_CREATOR ON SHARE_LINKS (CREATED_BY_USER_ID);
CREATE INDEX IX_SHARE_LINKS_RESOURCE ON SHARE_LINKS (RESOURCE_KIND, RESOURCE_ID);
COMMENT ON TABLE SHARE_LINKS IS 'Enlace caducable y revocable. RESOURCE_ID es referencia lógica (sin FK) validada por la aplicación según RESOURCE_KIND. Solo se guarda el hash del token.';
