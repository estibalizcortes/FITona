-- Diario: lo que realmente se ha comido.
CREATE TABLE FOOD_LOG_ENTRIES (
    ID               BYTEA DEFAULT decode(replace(gen_random_uuid()::text, '-', ''), 'hex') NOT NULL,
    USER_ID          BYTEA           NOT NULL,
    EATEN_ON         DATE              NOT NULL,
    MEAL_SLOT        VARCHAR(20) NOT NULL,
    EATEN_AT         TIMESTAMPTZ(6),
    LOG_METHOD       VARCHAR(12) NOT NULL,
    EATING_CONTEXT   VARCHAR(12),
    PLANNED_MEAL_ID  BYTEA,
    NOTE             VARCHAR(500),
    ROW_VERSION      BIGINT DEFAULT 0 NOT NULL,
    CREATED_AT       TIMESTAMPTZ(6) DEFAULT CURRENT_TIMESTAMP NOT NULL,
    UPDATED_AT       TIMESTAMPTZ(6) DEFAULT CURRENT_TIMESTAMP NOT NULL,
    DELETED_AT       TIMESTAMPTZ(6),
    SYNC_SEQ         BIGINT NOT NULL,
    CONSTRAINT PK_FOOD_LOG_ENTRIES PRIMARY KEY (ID),
    CONSTRAINT FK_FOOD_LOG_ENTRIES_USER FOREIGN KEY (USER_ID) REFERENCES APP_USERS (ID) ON DELETE CASCADE,
    CONSTRAINT FK_FOOD_LOG_ENTRIES_PLANNED FOREIGN KEY (PLANNED_MEAL_ID) REFERENCES PLANNED_MEALS (ID) ON DELETE SET NULL,
    CONSTRAINT CK_FOOD_LOG_ENTRIES_SLOT CHECK (MEAL_SLOT IN ('BREAKFAST','MID_MORNING','LUNCH','AFTERNOON_SNACK','DINNER','OTHER')),
    CONSTRAINT CK_FOOD_LOG_ENTRIES_METHOD CHECK (LOG_METHOD IN
        ('SEARCH','FREQUENT','REPEAT','VOICE','TEXT','PHOTO','BARCODE','PLAN','ASSISTANT','ESTIMATE','QUICK_NOTE','IMPORT')),
    CONSTRAINT CK_FOOD_LOG_ENTRIES_CONTEXT CHECK (EATING_CONTEXT IS NULL OR EATING_CONTEXT IN
        ('HOME','FAMILY','RESTAURANT','BAR','CAFE','CANTEEN','WORK','TRAVEL','OTHER'))
);
CREATE INDEX IX_FOOD_LOG_ENTRIES_DAY ON FOOD_LOG_ENTRIES (USER_ID, EATEN_ON);
CREATE INDEX IX_FOOD_LOG_ENTRIES_SYNC ON FOOD_LOG_ENTRIES (USER_ID, SYNC_SEQ);
CREATE INDEX IX_FOOD_LOG_ENTRIES_PLANNED ON FOOD_LOG_ENTRIES (PLANNED_MEAL_ID);
COMMENT ON TABLE FOOD_LOG_ENTRIES IS 'Comida consumida (siempre personal, nunca del hogar). PLANNED_MEAL_ID enlaza con el plan cuando la comida procede de él.';

CREATE TABLE FOOD_LOG_ITEMS (
    ID                  BYTEA DEFAULT decode(replace(gen_random_uuid()::text, '-', ''), 'hex') NOT NULL,
    ENTRY_ID            BYTEA            NOT NULL,
    SORT_ORDER          INTEGER DEFAULT 0 NOT NULL,
    ITEM_KIND           VARCHAR(16)  NOT NULL,
    VARIANT_ID          BIGINT,
    PRODUCT_ID          BIGINT,
    RECIPE_VERSION_ID   BYTEA,
    PREPARED_BATCH_ID   BYTEA,
    DISPLAY_NAME        VARCHAR(200) NOT NULL,
    QUANTITY            NUMERIC(10,3),
    UNIT_CODE           VARCHAR(20),
    GRAMS               NUMERIC(9,2),
    QUANTITY_SPECIFIED  BOOLEAN DEFAULT TRUE NOT NULL,
    SERVINGS            NUMERIC(6,2),
    ESTIMATE_MODIFIERS  JSONB,
    ENERGY_KCAL         NUMERIC(8,2),
    ENERGY_KCAL_LOW     NUMERIC(8,2),
    ENERGY_KCAL_HIGH    NUMERIC(8,2),
    PROTEIN_G           NUMERIC(7,2),
    CARBS_G             NUMERIC(7,2),
    SUGARS_G            NUMERIC(7,2),
    FAT_G               NUMERIC(7,2),
    SAT_FAT_G           NUMERIC(7,2),
    FIBER_G             NUMERIC(7,2),
    SALT_G              NUMERIC(7,3),
    ALCOHOL_G           NUMERIC(7,2),
    NUTRIENT_EXTRAS     JSONB,
    DATA_QUALITY        VARCHAR(10)  NOT NULL,
    NUTRIENT_PROFILE_ID BIGINT,
    CATALOG_RELEASE_ID  BIGINT,
    CONSTRAINT PK_FOOD_LOG_ITEMS PRIMARY KEY (ID),
    CONSTRAINT FK_FOOD_LOG_ITEMS_ENTRY FOREIGN KEY (ENTRY_ID) REFERENCES FOOD_LOG_ENTRIES (ID) ON DELETE CASCADE,
    CONSTRAINT FK_FOOD_LOG_ITEMS_VARIANT FOREIGN KEY (VARIANT_ID) REFERENCES FOOD_VARIANTS (ID) ON DELETE SET NULL,
    CONSTRAINT FK_FOOD_LOG_ITEMS_PRODUCT FOREIGN KEY (PRODUCT_ID) REFERENCES COMMERCIAL_PRODUCTS (ID) ON DELETE SET NULL,
    CONSTRAINT FK_FOOD_LOG_ITEMS_RECIPE FOREIGN KEY (RECIPE_VERSION_ID) REFERENCES RECIPE_VERSIONS (ID) ON DELETE SET NULL,
    CONSTRAINT FK_FOOD_LOG_ITEMS_BATCH FOREIGN KEY (PREPARED_BATCH_ID) REFERENCES PREPARED_BATCHES (ID) ON DELETE SET NULL,
    CONSTRAINT FK_FOOD_LOG_ITEMS_UNIT FOREIGN KEY (UNIT_CODE) REFERENCES PORTION_UNITS (CODE),
    CONSTRAINT FK_FOOD_LOG_ITEMS_PROFILE FOREIGN KEY (NUTRIENT_PROFILE_ID) REFERENCES NUTRIENT_PROFILES (ID) ON DELETE SET NULL,
    CONSTRAINT FK_FOOD_LOG_ITEMS_RELEASE FOREIGN KEY (CATALOG_RELEASE_ID) REFERENCES CATALOG_RELEASES (ID) ON DELETE SET NULL,
    CONSTRAINT CK_FOOD_LOG_ITEMS_KIND CHECK (ITEM_KIND IN ('FOOD','PRODUCT','RECIPE','BATCH','ESTIMATED_DISH','FREE_TEXT')),
    CONSTRAINT CK_FOOD_LOG_ITEMS_QUALITY CHECK (DATA_QUALITY IN ('VERIFIED','AVERAGE','ESTIMATE','CUSTOM','NONE')),
    CONSTRAINT CK_FOOD_LOG_ITEMS_FREE_TEXT CHECK (ITEM_KIND <> 'FREE_TEXT' OR (ENERGY_KCAL IS NULL AND DATA_QUALITY = 'NONE')),
    CONSTRAINT CK_FOOD_LOG_ITEMS_RANGE CHECK (
        (ENERGY_KCAL_LOW IS NULL AND ENERGY_KCAL_HIGH IS NULL)
        OR (ENERGY_KCAL_LOW <= ENERGY_KCAL AND ENERGY_KCAL <= ENERGY_KCAL_HIGH)),
    CONSTRAINT CK_FOOD_LOG_ITEMS_POSITIVE CHECK (
        COALESCE(GRAMS,0) >= 0 AND COALESCE(ENERGY_KCAL,0) >= 0 AND COALESCE(PROTEIN_G,0) >= 0 AND COALESCE(CARBS_G,0) >= 0
        AND COALESCE(FAT_G,0) >= 0 AND COALESCE(FIBER_G,0) >= 0)
);
CREATE INDEX IX_FOOD_LOG_ITEMS_ENTRY ON FOOD_LOG_ITEMS (ENTRY_ID, SORT_ORDER);
CREATE INDEX IX_FOOD_LOG_ITEMS_VARIANT ON FOOD_LOG_ITEMS (VARIANT_ID);
CREATE INDEX IX_FOOD_LOG_ITEMS_PRODUCT ON FOOD_LOG_ITEMS (PRODUCT_ID);
CREATE INDEX IX_FOOD_LOG_ITEMS_RECIPE ON FOOD_LOG_ITEMS (RECIPE_VERSION_ID);
CREATE INDEX IX_FOOD_LOG_ITEMS_BATCH ON FOOD_LOG_ITEMS (PREPARED_BATCH_ID);
CREATE INDEX IX_FOOD_LOG_ITEMS_UNIT ON FOOD_LOG_ITEMS (UNIT_CODE);
CREATE INDEX IX_FOOD_LOG_ITEMS_PROFILE ON FOOD_LOG_ITEMS (NUTRIENT_PROFILE_ID);
CREATE INDEX IX_FOOD_LOG_ITEMS_RELEASE ON FOOD_LOG_ITEMS (CATALOG_RELEASE_ID);
COMMENT ON TABLE FOOD_LOG_ITEMS IS 'Elementos consumidos con INSTANTÁNEA nutricional: si el catálogo cambia, el histórico no cambia. FREE_TEXT = registro sin cifras ("lentejas de mi madre").';
COMMENT ON COLUMN FOOD_LOG_ITEMS.QUANTITY_SPECIFIED IS 'FALSE si la persona no indicó cantidad: se usó la ración por defecto y se muestra como estimación.';
COMMENT ON COLUMN FOOD_LOG_ITEMS.ESTIMATE_MODIFIERS IS 'Ajustes de un plato estimado: {"portion":"LARGE","oil":"HIGH"}.';

