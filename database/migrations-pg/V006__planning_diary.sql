-- FITona · V006 · Planificación flexible y diario real
-- Plan (lo propuesto) y diario (lo comido) son registros independientes:
-- cambiar lo que se come nunca reescribe el plan, y viceversa.
-- =============================================================================

CREATE TABLE MEAL_PLANS (
    ID                    BYTEA DEFAULT decode(replace(gen_random_uuid()::text, '-', ''), 'hex') NOT NULL,
    HOUSEHOLD_ID          BYTEA           NOT NULL,
    CREATED_BY_USER_ID    BYTEA,
    TITLE                 VARCHAR(120),
    START_DATE            DATE              NOT NULL,
    END_DATE              DATE              NOT NULL,
    STATUS                VARCHAR(10) DEFAULT 'ACTIVE' NOT NULL,
    PLAN_ORIGIN           VARCHAR(12) DEFAULT 'MANUAL' NOT NULL,
    COPIED_FROM_PLAN_ID   BYTEA,
    NUTRITION_TARGET_ID   BYTEA,
    GENERATION_PARAMS     JSONB,
    ROW_VERSION           BIGINT DEFAULT 0 NOT NULL,
    CREATED_AT            TIMESTAMPTZ(6) DEFAULT CURRENT_TIMESTAMP NOT NULL,
    UPDATED_AT            TIMESTAMPTZ(6) DEFAULT CURRENT_TIMESTAMP NOT NULL,
    DELETED_AT            TIMESTAMPTZ(6),
    SYNC_SEQ              BIGINT NOT NULL,
    CONSTRAINT PK_MEAL_PLANS PRIMARY KEY (ID),
    CONSTRAINT FK_MEAL_PLANS_HOUSEHOLD FOREIGN KEY (HOUSEHOLD_ID) REFERENCES HOUSEHOLDS (ID) ON DELETE CASCADE,
    CONSTRAINT FK_MEAL_PLANS_CREATOR FOREIGN KEY (CREATED_BY_USER_ID) REFERENCES APP_USERS (ID) ON DELETE SET NULL,
    CONSTRAINT FK_MEAL_PLANS_COPIED_FROM FOREIGN KEY (COPIED_FROM_PLAN_ID) REFERENCES MEAL_PLANS (ID) ON DELETE SET NULL,
    CONSTRAINT FK_MEAL_PLANS_TARGET FOREIGN KEY (NUTRITION_TARGET_ID) REFERENCES NUTRITION_TARGETS (ID) ON DELETE SET NULL,
    CONSTRAINT CK_MEAL_PLANS_DATES CHECK (END_DATE >= START_DATE AND END_DATE - START_DATE <= 30),
    CONSTRAINT CK_MEAL_PLANS_STATUS CHECK (STATUS IN ('DRAFT','ACTIVE','PAUSED','ARCHIVED')),
    CONSTRAINT CK_MEAL_PLANS_ORIGIN CHECK (PLAN_ORIGIN IN ('MANUAL','ASSISTANT','COPIED','TEMPLATE'))
);
CREATE INDEX IX_MEAL_PLANS_HOUSEHOLD ON MEAL_PLANS (HOUSEHOLD_ID, START_DATE);
CREATE INDEX IX_MEAL_PLANS_SYNC ON MEAL_PLANS (HOUSEHOLD_ID, SYNC_SEQ);
CREATE INDEX IX_MEAL_PLANS_CREATOR ON MEAL_PLANS (CREATED_BY_USER_ID);
CREATE INDEX IX_MEAL_PLANS_COPIED_FROM ON MEAL_PLANS (COPIED_FROM_PLAN_ID);
CREATE INDEX IX_MEAL_PLANS_TARGET ON MEAL_PLANS (NUTRITION_TARGET_ID);
COMMENT ON TABLE MEAL_PLANS IS 'Plan de 1 a 31 días (mañana, 3 días, semana...). PAUSED = modo viaje: se conserva sin aplicarse.';

ALTER TABLE SHOPPING_LISTS ADD CONSTRAINT FK_SHOPPING_LISTS_PLAN
    FOREIGN KEY (MEAL_PLAN_ID) REFERENCES MEAL_PLANS (ID) ON DELETE SET NULL;

