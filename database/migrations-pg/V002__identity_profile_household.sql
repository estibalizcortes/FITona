    CONSTRAINT FK_HOUSEHOLD_INV_CREATOR FOREIGN KEY (CREATED_BY_USER_ID) REFERENCES APP_USERS (ID) ON DELETE CASCADE,
    CONSTRAINT FK_HOUSEHOLD_INV_ACCEPTED FOREIGN KEY (ACCEPTED_BY_USER_ID) REFERENCES APP_USERS (ID) ON DELETE SET NULL
