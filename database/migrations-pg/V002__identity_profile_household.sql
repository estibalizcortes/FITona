CREATE INDEX IX_HOUSEHOLD_INV_HOUSEHOLD ON HOUSEHOLD_INVITATIONS (HOUSEHOLD_ID);
CREATE INDEX IX_HOUSEHOLD_INV_CREATOR ON HOUSEHOLD_INVITATIONS (CREATED_BY_USER_ID);
CREATE INDEX IX_HOUSEHOLD_INV_ACCEPTED ON HOUSEHOLD_INVITATIONS (ACCEPTED_BY_USER_ID);
COMMENT ON TABLE HOUSEHOLD_INVITATIONS IS 'Invitaciones a un hogar. Solo se guarda el hash del token (nunca el token).';
