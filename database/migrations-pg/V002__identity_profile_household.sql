-- Objetivos nutricionales opcionales, expresados como rangos y con vigencia.
CREATE TABLE NUTRITION_TARGETS (
    ID                    BYTEA DEFAULT decode(replace(gen_random_uuid()::text, '-', ''), 'hex') NOT NULL,
    USER_ID               BYTEA NOT NULL,
    VALID_FROM            DATE    NOT NULL,
    VALID_TO              DATE,
    ENERGY_KCAL_MIN       NUMERIC(6,1),
    ENERGY_KCAL_MAX       NUMERIC(6,1),
    PROTEIN_G_MIN         NUMERIC(6,1),
    PROTEIN_G_MAX         NUMERIC(6,1),
    CARBS_G_MIN           NUMERIC(6,1),
    CARBS_G_MAX           NUMERIC(6,1),
    FAT_G_MIN             NUMERIC(6,1),
    FAT_G_MAX             NUMERIC(6,1),
    FIBER_G_MIN           NUMERIC(6,1),
    TARGET_ORIGIN         VARCHAR(30) NOT NULL,
    ENERGY_RECONCILIATION VARCHAR(30),
    NOTE                  VARCHAR(500),
    CREATED_AT            TIMESTAMPTZ(6) DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT PK_NUTRITION_TARGETS PRIMARY KEY (ID),
    CONSTRAINT FK_NUTRITION_TARGETS_USER FOREIGN KEY (USER_ID) REFERENCES APP_USERS (ID) ON DELETE CASCADE,
    CONSTRAINT CK_NUTRITION_TARGETS_DATES CHECK (VALID_TO IS NULL OR VALID_TO >= VALID_FROM),
    CONSTRAINT CK_NUTRITION_TARGETS_RANGES CHECK (
        (ENERGY_KCAL_MIN IS NULL OR ENERGY_KCAL_MAX IS NULL OR ENERGY_KCAL_MIN <= ENERGY_KCAL_MAX)
        AND (PROTEIN_G_MIN IS NULL OR PROTEIN_G_MAX IS NULL OR PROTEIN_G_MIN <= PROTEIN_G_MAX)
        AND (CARBS_G_MIN IS NULL OR CARBS_G_MAX IS NULL OR CARBS_G_MIN <= CARBS_G_MAX)
        AND (FAT_G_MIN IS NULL OR FAT_G_MAX IS NULL OR FAT_G_MIN <= FAT_G_MAX)),
    CONSTRAINT CK_NUTRITION_TARGETS_POSITIVE CHECK (
        COALESCE(ENERGY_KCAL_MIN,0) >= 0 AND COALESCE(PROTEIN_G_MIN,0) >= 0 AND COALESCE(CARBS_G_MIN,0) >= 0
        AND COALESCE(FAT_G_MIN,0) >= 0 AND COALESCE(FIBER_G_MIN,0) >= 0),
    CONSTRAINT CK_NUTRITION_TARGETS_ORIGIN CHECK (TARGET_ORIGIN IN ('USER','PROFESSIONAL','ASSISTANT_CONFIRMED')),
    CONSTRAINT CK_NUTRITION_TARGETS_RECON CHECK (ENERGY_RECONCILIATION IS NULL OR ENERGY_RECONCILIATION IN
        ('KEEP_BOTH','ENERGY_FROM_MACROS','ADJUST_CARBS','ADJUST_FAT','ADJUST_PROTEIN'))
);
CREATE INDEX IX_NUTRITION_TARGETS_USER ON NUTRITION_TARGETS (USER_ID, VALID_FROM);
COMMENT ON TABLE NUTRITION_TARGETS IS 'Objetivos opcionales (solo modo avanzado). Rango min/max; un valor exacto es min=max. Nunca se modifican de forma automática.';
COMMENT ON COLUMN NUTRITION_TARGETS.ENERGY_RECONCILIATION IS 'Decisión explícita de la persona cuando kcal y macros (4/4/9) no cuadran.';

-- Hogares: unidad de compartición de despensa, compra y planes.
CREATE TABLE HOUSEHOLDS (
    ID                  BYTEA DEFAULT decode(replace(gen_random_uuid()::text, '-', ''), 'hex') NOT NULL,
    NAME                VARCHAR(80) NOT NULL,
    IS_PERSONAL         BOOLEAN DEFAULT TRUE NOT NULL,
    CREATED_BY_USER_ID  BYTEA,
    COUNTRY_CODE        VARCHAR(2) DEFAULT 'ES' NOT NULL,
    CURRENCY_CODE       VARCHAR(3) DEFAULT 'EUR' NOT NULL,
    ROW_VERSION         BIGINT DEFAULT 0 NOT NULL,
    CREATED_AT          TIMESTAMPTZ(6) DEFAULT CURRENT_TIMESTAMP NOT NULL,
    UPDATED_AT          TIMESTAMPTZ(6) DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT PK_HOUSEHOLDS PRIMARY KEY (ID),
    CONSTRAINT FK_HOUSEHOLDS_CREATOR FOREIGN KEY (CREATED_BY_USER_ID) REFERENCES APP_USERS (ID) ON DELETE SET NULL
);
CREATE INDEX IX_HOUSEHOLDS_CREATOR ON HOUSEHOLDS (CREATED_BY_USER_ID);
COMMENT ON TABLE HOUSEHOLDS IS 'Cada cuenta tiene un hogar personal; los hogares compartidos se crean al invitar. Los diarios de comida NUNCA pertenecen al hogar, solo a la persona.';

CREATE TABLE HOUSEHOLD_MEMBERS (
    HOUSEHOLD_ID  BYTEA           NOT NULL,
    USER_ID       BYTEA           NOT NULL,
    MEMBER_ROLE   VARCHAR(10) DEFAULT 'MEMBER' NOT NULL,
    JOINED_AT     TIMESTAMPTZ(6) DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT PK_HOUSEHOLD_MEMBERS PRIMARY KEY (HOUSEHOLD_ID, USER_ID),
    CONSTRAINT FK_HOUSEHOLD_MEMBERS_HOUSEHOLD FOREIGN KEY (HOUSEHOLD_ID) REFERENCES HOUSEHOLDS (ID) ON DELETE CASCADE,
    CONSTRAINT FK_HOUSEHOLD_MEMBERS_USER FOREIGN KEY (USER_ID) REFERENCES APP_USERS (ID) ON DELETE CASCADE,
    CONSTRAINT CK_HOUSEHOLD_MEMBERS_ROLE CHECK (MEMBER_ROLE IN ('OWNER','MEMBER'))
);
CREATE INDEX IX_HOUSEHOLD_MEMBERS_USER ON HOUSEHOLD_MEMBERS (USER_ID);
COMMENT ON TABLE HOUSEHOLD_MEMBERS IS 'Pertenencia a hogares. Base de toda autorización sobre despensa, compra y planes compartidos.';

CREATE TABLE HOUSEHOLD_INVITATIONS (
    ID                   BYTEA DEFAULT decode(replace(gen_random_uuid()::text, '-', ''), 'hex') NOT NULL,
    HOUSEHOLD_ID         BYTEA            NOT NULL,
    TOKEN_HASH           VARCHAR(128) NOT NULL,
    CREATED_BY_USER_ID   BYTEA            NOT NULL,
    EXPIRES_AT           TIMESTAMPTZ(6) NOT NULL,
    ACCEPTED_BY_USER_ID  BYTEA,
    ACCEPTED_AT          TIMESTAMPTZ(6),
    REVOKED_AT           TIMESTAMPTZ(6),
