-- Generador global para la sincronización incremental (ver docs/tecnico/E-arquitectura.md §7).
CREATE SEQUENCE SYNC_SEQ_GEN START WITH 1 INCREMENT BY 1 CACHE 100 NO CYCLE;

CREATE TABLE APP_USERS (
    ID                     BYTEA DEFAULT decode(replace(gen_random_uuid()::text, '-', ''), 'hex') NOT NULL,
    AUTH_SUBJECT           VARCHAR(255) NOT NULL,
    STATUS                 VARCHAR(20) DEFAULT 'ACTIVE' NOT NULL,
    LOCALE                 VARCHAR(10) DEFAULT 'es-ES' NOT NULL,
    TIME_ZONE              VARCHAR(40) DEFAULT 'Europe/Madrid' NOT NULL,
    COUNTRY_CODE           VARCHAR(2)  DEFAULT 'ES' NOT NULL,
    CURRENCY_CODE          VARCHAR(3)  DEFAULT 'EUR' NOT NULL,
    ADULT_CONFIRMED_AT     TIMESTAMPTZ(6),
    DELETION_REQUESTED_AT  TIMESTAMPTZ(6),
    ROW_VERSION            BIGINT DEFAULT 0 NOT NULL,
    CREATED_AT             TIMESTAMPTZ(6) DEFAULT CURRENT_TIMESTAMP NOT NULL,
    UPDATED_AT             TIMESTAMPTZ(6) DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT PK_APP_USERS PRIMARY KEY (ID),
    CONSTRAINT UK_APP_USERS_SUBJECT UNIQUE (AUTH_SUBJECT),
    CONSTRAINT CK_APP_USERS_STATUS CHECK (STATUS IN ('ACTIVE','SUSPENDED','PENDING_DELETION'))
);
COMMENT ON TABLE APP_USERS IS 'Cuenta de aplicación. Sin correo ni contraseña (están en Keycloak): minimización de datos. Borrar la fila elimina en cascada todos los datos personales.';
COMMENT ON COLUMN APP_USERS.AUTH_SUBJECT IS 'Claim sub del token OIDC.';
COMMENT ON COLUMN APP_USERS.ADULT_CONFIRMED_AT IS 'Momento en que la persona confirmó ser mayor de edad (v1 solo adultos). No se guarda la fecha de nacimiento.';

CREATE TABLE USER_PROFILES (
    USER_ID                  BYTEA NOT NULL,
    DISPLAY_NAME             VARCHAR(80),
    DISPLAY_MODE             VARCHAR(10) DEFAULT 'SIMPLE' NOT NULL,
    SHOW_ENERGY              BOOLEAN DEFAULT FALSE NOT NULL,
    SHOW_MACROS              BOOLEAN DEFAULT FALSE NOT NULL,
    SHOW_STATS               BOOLEAN DEFAULT FALSE NOT NULL,
    SHOW_BODY_MEASUREMENTS   BOOLEAN DEFAULT FALSE NOT NULL,
    DIET_PATTERN             VARCHAR(20) DEFAULT 'OMNIVORE' NOT NULL,
    COOKING_SKILL            VARCHAR(20),
    WEEKDAY_COOK_MINUTES     INTEGER,
    WEEKEND_COOK_MINUTES     INTEGER,
    DEFAULT_DINERS           INTEGER DEFAULT 1 NOT NULL,
    WEEKLY_BUDGET_AMOUNT     NUMERIC(10,2),
    ENABLED_MEAL_SLOTS       JSONB,
    LIFE_CONTEXTS            JSONB,
    PLANNING_PAUSED_UNTIL    DATE,
    REMINDERS_ENABLED        BOOLEAN DEFAULT FALSE NOT NULL,
    ROW_VERSION              BIGINT DEFAULT 0 NOT NULL,
    UPDATED_AT               TIMESTAMPTZ(6) DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT PK_USER_PROFILES PRIMARY KEY (USER_ID),
    CONSTRAINT FK_USER_PROFILES_USER FOREIGN KEY (USER_ID) REFERENCES APP_USERS (ID) ON DELETE CASCADE,
    CONSTRAINT CK_USER_PROFILES_MODE CHECK (DISPLAY_MODE IN ('SIMPLE','BALANCED','ADVANCED')),
    CONSTRAINT CK_USER_PROFILES_DIET CHECK (DIET_PATTERN IN ('OMNIVORE','VEGETARIAN','VEGAN','PESCATARIAN','OTHER')),
    CONSTRAINT CK_USER_PROFILES_SKILL CHECK (COOKING_SKILL IS NULL OR COOKING_SKILL IN ('BEGINNER','INTERMEDIATE','ADVANCED')),
    CONSTRAINT CK_USER_PROFILES_MINUTES CHECK (COALESCE(WEEKDAY_COOK_MINUTES,0) BETWEEN 0 AND 600 AND COALESCE(WEEKEND_COOK_MINUTES,0) BETWEEN 0 AND 600),
    CONSTRAINT CK_USER_PROFILES_DINERS CHECK (DEFAULT_DINERS BETWEEN 1 AND 30),
    CONSTRAINT CK_USER_PROFILES_BUDGET CHECK (WEEKLY_BUDGET_AMOUNT IS NULL OR WEEKLY_BUDGET_AMOUNT >= 0),
    CONSTRAINT CK_USER_PROFILES_SLOTS CHECK (ENABLED_MEAL_SLOTS IS NULL OR JSON_EXISTS(ENABLED_MEAL_SLOTS, '$[0]')),
    CONSTRAINT CK_USER_PROFILES_CONTEXTS CHECK (LIFE_CONTEXTS IS NULL OR JSON_EXISTS(LIFE_CONTEXTS, '$[*]'))
);
COMMENT ON TABLE USER_PROFILES IS 'Preferencias de experiencia. Los "modos" (estudiante, familiar, poco tiempo...) son combinaciones de estas preferencias, no pantallas distintas.';
COMMENT ON COLUMN USER_PROFILES.DISPLAY_MODE IS 'SIMPLE: sin cifras; BALANCED: cifras aproximadas sin objetivos; ADVANCED: cifras, objetivos y estadísticas. Cambiar de modo nunca borra datos.';
COMMENT ON COLUMN USER_PROFILES.ENABLED_MEAL_SLOTS IS 'Array JSON de franjas activas, p. ej. ["BREAKFAST","LUNCH","AFTERNOON_SNACK","DINNER"].';
COMMENT ON COLUMN USER_PROFILES.LIFE_CONTEXTS IS 'Array JSON: STUDENT, FAMILY, LOW_TIME, TIGHT_BUDGET, TRAVEL, BATCH_COOKING.';
COMMENT ON COLUMN USER_PROFILES.PLANNING_PAUSED_UNTIL IS 'Modo viaje: la planificación queda en pausa sin borrarse hasta esta fecha.';

CREATE TABLE USER_GOAL_INTENTS (
    USER_ID      BYTEA           NOT NULL,
    INTENT_CODE  VARCHAR(30) NOT NULL,
    CREATED_AT   TIMESTAMPTZ(6) DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT PK_USER_GOAL_INTENTS PRIMARY KEY (USER_ID, INTENT_CODE),
    CONSTRAINT FK_USER_GOAL_INTENTS_USER FOREIGN KEY (USER_ID) REFERENCES APP_USERS (ID) ON DELETE CASCADE,
    CONSTRAINT CK_USER_GOAL_INTENTS_CODE CHECK (INTENT_CODE IN
        ('ORGANIZE_MEALS','KNOW_WHAT_I_EAT','NUTRITION_TARGETS','SPORT','FAMILY_PLANNING','SAVE_MONEY','COOK_WITH_WHAT_I_HAVE','LEARN_TO_COOK'))
);
COMMENT ON TABLE USER_GOAL_INTENTS IS 'Qué busca la persona (respuesta del onboarding). Adapta la experiencia; no es un objetivo numérico. FK cubierta por la PK.';

-- Registro inmutable de decisiones de consentimiento (RGPD art. 7 y 9).
CREATE TABLE USER_CONSENTS (
    ID              BIGINT GENERATED BY DEFAULT AS IDENTITY,
    USER_ID         BYTEA           NOT NULL,
    CONSENT_CODE    VARCHAR(40) NOT NULL,
    POLICY_VERSION  VARCHAR(20) NOT NULL,
    GRANTED         BOOLEAN           NOT NULL,
    DECIDED_AT      TIMESTAMPTZ(6) DEFAULT CURRENT_TIMESTAMP NOT NULL,
    DECISION_SOURCE VARCHAR(20) NOT NULL,
    CONSTRAINT PK_USER_CONSENTS PRIMARY KEY (ID),
    CONSTRAINT FK_USER_CONSENTS_USER FOREIGN KEY (USER_ID) REFERENCES APP_USERS (ID) ON DELETE CASCADE,
    CONSTRAINT CK_USER_CONSENTS_CODE CHECK (CONSENT_CODE IN
        ('HEALTH_DATA_PROCESSING','AI_PROCESSING','AI_SHARE_DIARY','AI_SHARE_PANTRY','AI_SHARE_PREFERENCES',
         'AI_SHARE_ACTIVITY','AI_SHARE_PHOTOS','PRODUCT_ANALYTICS','SHARE_PRICES_COMMUNITY','MARKETING_EMAIL')),
    CONSTRAINT CK_USER_CONSENTS_SOURCE CHECK (DECISION_SOURCE IN ('ONBOARDING','SETTINGS','FEATURE_PROMPT','SUPPORT'))
);
CREATE INDEX IX_USER_CONSENTS_USER ON USER_CONSENTS (USER_ID, CONSENT_CODE, DECIDED_AT);
COMMENT ON TABLE USER_CONSENTS IS 'Historial de consentimientos (solo inserciones). El estado vigente es la última decisión por código. Retirar = nueva fila con GRANTED=FALSE.';

CREATE TABLE USER_ALLERGENS (
