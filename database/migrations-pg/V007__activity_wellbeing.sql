CREATE TABLE ACTIVITY_LOGS (
    ID                  BYTEA DEFAULT decode(replace(gen_random_uuid()::text, '-', ''), 'hex') NOT NULL,
    USER_ID             BYTEA           NOT NULL,
    ACTIVITY_TYPE_CODE  VARCHAR(30) NOT NULL,
    STARTED_AT          TIMESTAMPTZ(6) NOT NULL,
    DURATION_SECONDS    INTEGER,
    DISTANCE_M          NUMERIC(9,1),
    STEPS               INTEGER,
    ELEVATION_GAIN_M    NUMERIC(6,1),
    AVG_SPEED_KMH       NUMERIC(5,2),
    ENERGY_KCAL_EST     NUMERIC(6,1),
    FIELD_ORIGINS       JSONB,
    SOURCE_KIND         VARCHAR(16) DEFAULT 'MANUAL' NOT NULL,
    EXTERNAL_ID         VARCHAR(100),
    DEDUP_FINGERPRINT   VARCHAR(64),
    NOTE                VARCHAR(500),
    ROW_VERSION         BIGINT DEFAULT 0 NOT NULL,
    CREATED_AT          TIMESTAMPTZ(6) DEFAULT CURRENT_TIMESTAMP NOT NULL,
    UPDATED_AT          TIMESTAMPTZ(6) DEFAULT CURRENT_TIMESTAMP NOT NULL,
    DELETED_AT          TIMESTAMPTZ(6),
    SYNC_SEQ            BIGINT NOT NULL,
    CONSTRAINT PK_ACTIVITY_LOGS PRIMARY KEY (ID),
    CONSTRAINT FK_ACTIVITY_LOGS_USER FOREIGN KEY (USER_ID) REFERENCES APP_USERS (ID) ON DELETE CASCADE,
    CONSTRAINT FK_ACTIVITY_LOGS_TYPE FOREIGN KEY (ACTIVITY_TYPE_CODE) REFERENCES ACTIVITY_TYPES (CODE),
    CONSTRAINT CK_ACTIVITY_LOGS_SOURCE CHECK (SOURCE_KIND IN
        ('MANUAL','SCREENSHOT','FILE_IMPORT','STRAVA','GARMIN','HEALTH_CONNECT','HEALTHKIT')),
    CONSTRAINT CK_ACTIVITY_LOGS_VALUES CHECK (
        COALESCE(DURATION_SECONDS,0) BETWEEN 0 AND 172800 AND COALESCE(DISTANCE_M,0) >= 0 AND COALESCE(STEPS,0) >= 0
        AND COALESCE(ENERGY_KCAL_EST,0) >= 0 AND COALESCE(AVG_SPEED_KMH,0) BETWEEN 0 AND 120),
    CONSTRAINT CK_ACTIVITY_LOGS_EXTERNAL CHECK (SOURCE_KIND IN ('MANUAL','SCREENSHOT') OR EXTERNAL_ID IS NOT NULL OR DEDUP_FINGERPRINT IS NOT NULL)
);
CREATE UNIQUE INDEX UX_ACTIVITY_LOGS_EXTERNAL ON ACTIVITY_LOGS ((CASE WHEN EXTERNAL_ID IS NOT NULL THEN USER_ID END),
                                                              (CASE WHEN EXTERNAL_ID IS NOT NULL THEN SOURCE_KIND END),
                                                              EXTERNAL_ID);
CREATE INDEX IX_ACTIVITY_LOGS_DAY ON ACTIVITY_LOGS (USER_ID, STARTED_AT);
CREATE INDEX IX_ACTIVITY_LOGS_SYNC ON ACTIVITY_LOGS (USER_ID, SYNC_SEQ);
CREATE INDEX IX_ACTIVITY_LOGS_TYPE ON ACTIVITY_LOGS (ACTIVITY_TYPE_CODE);
CREATE INDEX IX_ACTIVITY_LOGS_FINGERPRINT ON ACTIVITY_LOGS (USER_ID, DEDUP_FINGERPRINT);
COMMENT ON TABLE ACTIVITY_LOGS IS 'Actividad. Antiduplicados: único por (persona, fuente, id externo) + huella temporal (inicio redondeado + duración + tipo) para cruces entre fuentes.';
COMMENT ON COLUMN ACTIVITY_LOGS.FIELD_ORIGINS IS 'Origen por campo: {"distanceM":"OBSERVED","avgSpeedKmh":"CALCULATED","energyKcalEst":"ESTIMATED"}.';
COMMENT ON COLUMN ACTIVITY_LOGS.ENERGY_KCAL_EST IS 'Opcional e informativo. Oculto por defecto. Jamás se suma al presupuesto de comida.';

CREATE TABLE USER_INTEGRATIONS (
    ID                    BYTEA DEFAULT decode(replace(gen_random_uuid()::text, '-', ''), 'hex') NOT NULL,
    USER_ID               BYTEA           NOT NULL,
    PROVIDER              VARCHAR(20) NOT NULL,
    STATUS                VARCHAR(12) DEFAULT 'CONNECTED' NOT NULL,
    SCOPES                VARCHAR(500),
    EXTERNAL_ACCOUNT_ID   VARCHAR(100),
    ACCESS_TOKEN_ENC      BYTEA,
    REFRESH_TOKEN_ENC     BYTEA,
    TOKEN_KEY_ID          VARCHAR(60),
    TOKEN_EXPIRES_AT      TIMESTAMPTZ(6),
    LAST_SYNC_AT          TIMESTAMPTZ(6),
    LAST_ERROR_CODE       VARCHAR(60),
    CONNECTED_AT          TIMESTAMPTZ(6) DEFAULT CURRENT_TIMESTAMP NOT NULL,
    DISCONNECTED_AT       TIMESTAMPTZ(6),
    CONSTRAINT PK_USER_INTEGRATIONS PRIMARY KEY (ID),
    CONSTRAINT UK_USER_INTEGRATIONS UNIQUE (USER_ID, PROVIDER),
    CONSTRAINT FK_USER_INTEGRATIONS_USER FOREIGN KEY (USER_ID) REFERENCES APP_USERS (ID) ON DELETE CASCADE,
    CONSTRAINT CK_USER_INTEGRATIONS_PROVIDER CHECK (PROVIDER IN ('STRAVA','GARMIN','HEALTH_CONNECT','HEALTHKIT')),
    CONSTRAINT CK_USER_INTEGRATIONS_STATUS CHECK (STATUS IN ('CONNECTED','ERROR','REVOKED','DISCONNECTED'))
);
COMMENT ON TABLE USER_INTEGRATIONS IS 'Conexiones con servicios externos. Tokens cifrados en la aplicación (cifrado sobre, clave fuera de la BD; TOKEN_KEY_ID permite rotación). Health Connect/HealthKit se leen en el dispositivo y no guardan tokens. FK cubierta por UK_USER_INTEGRATIONS.';

CREATE TABLE WELLBEING_ENTRIES (
    ID             BYTEA DEFAULT decode(replace(gen_random_uuid()::text, '-', ''), 'hex') NOT NULL,
    USER_ID        BYTEA NOT NULL,
    ENTRY_DATE     DATE    NOT NULL,
    SLEEP_HOURS    NUMERIC(4,2),
    ENERGY_LEVEL   INTEGER,
    NOTE           VARCHAR(1000),
    ROW_VERSION    BIGINT DEFAULT 0 NOT NULL,
    CREATED_AT     TIMESTAMPTZ(6) DEFAULT CURRENT_TIMESTAMP NOT NULL,
    UPDATED_AT     TIMESTAMPTZ(6) DEFAULT CURRENT_TIMESTAMP NOT NULL,
    DELETED_AT     TIMESTAMPTZ(6),
    SYNC_SEQ       BIGINT NOT NULL,
    CONSTRAINT PK_WELLBEING_ENTRIES PRIMARY KEY (ID),
    CONSTRAINT UK_WELLBEING_ENTRIES_DAY UNIQUE (USER_ID, ENTRY_DATE),
    CONSTRAINT FK_WELLBEING_ENTRIES_USER FOREIGN KEY (USER_ID) REFERENCES APP_USERS (ID) ON DELETE CASCADE,
    CONSTRAINT CK_WELLBEING_SLEEP CHECK (SLEEP_HOURS IS NULL OR SLEEP_HOURS BETWEEN 0 AND 24),
    CONSTRAINT CK_WELLBEING_ENERGY CHECK (ENERGY_LEVEL IS NULL OR ENERGY_LEVEL BETWEEN 1 AND 5)
);
CREATE INDEX IX_WELLBEING_ENTRIES_SYNC ON WELLBEING_ENTRIES (USER_ID, SYNC_SEQ);
COMMENT ON TABLE WELLBEING_ENTRIES IS 'Opcional y desactivado por defecto: horas de sueño, energía percibida (1-5) y nota privada. Sin puntuaciones de salud. FK cubierta por UK_WELLBEING_ENTRIES_DAY.';

CREATE TABLE BODY_MEASUREMENTS (
    ID             BYTEA DEFAULT decode(replace(gen_random_uuid()::text, '-', ''), 'hex') NOT NULL,
    USER_ID        BYTEA      NOT NULL,
    MEASURED_ON    DATE         NOT NULL,
    WEIGHT_KG      NUMERIC(5,2)  NOT NULL,
    ROW_VERSION    BIGINT DEFAULT 0 NOT NULL,
    CREATED_AT     TIMESTAMPTZ(6) DEFAULT CURRENT_TIMESTAMP NOT NULL,
    UPDATED_AT     TIMESTAMPTZ(6) DEFAULT CURRENT_TIMESTAMP NOT NULL,
    DELETED_AT     TIMESTAMPTZ(6),
    SYNC_SEQ       BIGINT NOT NULL,
    CONSTRAINT PK_BODY_MEASUREMENTS PRIMARY KEY (ID),
    CONSTRAINT FK_BODY_MEASUREMENTS_USER FOREIGN KEY (USER_ID) REFERENCES APP_USERS (ID) ON DELETE CASCADE,
    CONSTRAINT CK_BODY_MEASUREMENTS_WEIGHT CHECK (WEIGHT_KG BETWEEN 20 AND 400)
);
CREATE INDEX IX_BODY_MEASUREMENTS_USER ON BODY_MEASUREMENTS (USER_ID, MEASURED_ON);
CREATE INDEX IX_BODY_MEASUREMENTS_SYNC ON BODY_MEASUREMENTS (USER_ID, SYNC_SEQ);
COMMENT ON TABLE BODY_MEASUREMENTS IS 'Pesaje opcional, oculto por defecto (USER_PROFILES.SHOW_BODY_MEASUREMENTS). Ninguna función lo exige ni fija objetivos de pérdida de peso.';
