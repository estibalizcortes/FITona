-- =============================================================================
-- FITona · V003 · Catálogo nutricional en tres niveles
--   Nivel 1 FOODS              alimento genérico (lo que ve la persona)
--   Nivel 2 FOOD_VARIANTS      variante nutricional (crudo/cocido, con/sin azúcar...)
--   Nivel 3 COMMERCIAL_PRODUCTS producto de marca (opcional, vinculado a una variante)
-- Los valores nutricionales viven en NUTRIENT_PROFILES (inmutables una vez aprobados)
-- y conservan su procedencia (SOURCE_RECORDS + PROFILE_CONTRIBUTIONS).
-- =============================================================================

CREATE TABLE CATALOG_RELEASES (
    ID              BIGINT GENERATED BY DEFAULT AS IDENTITY,
    VERSION_LABEL   VARCHAR(30) NOT NULL,
    STATUS          VARCHAR(10) DEFAULT 'DRAFT' NOT NULL,
    PUBLISHED_AT    TIMESTAMPTZ(6),
    PUBLISHED_BY    VARCHAR(255),
    NOTES           VARCHAR(2000),
    CONSTRAINT PK_CATALOG_RELEASES PRIMARY KEY (ID),
    CONSTRAINT UK_CATALOG_RELEASES_LABEL UNIQUE (VERSION_LABEL),
    CONSTRAINT CK_CATALOG_RELEASES_STATUS CHECK (STATUS IN ('DRAFT','PUBLISHED','WITHDRAWN'))
);
COMMENT ON TABLE CATALOG_RELEASES IS 'Versiones publicadas del catálogo. Los clientes descargan el catálogo esencial por versión (uso sin conexión).';

