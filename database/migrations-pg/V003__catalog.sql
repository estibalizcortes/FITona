COMMENT ON TABLE IMPORT_BATCHES IS 'Ejecuciones de importación desde fuentes externas, con contadores para el panel de administración.';

-- Perfil nutricional por 100 g o 100 ml. NULL = desconocido (nunca equivale a 0).
CREATE TABLE NUTRIENT_PROFILES (
    ID               BIGINT GENERATED BY DEFAULT AS IDENTITY,
    PROFILE_ROLE     VARCHAR(20) NOT NULL,
    BASIS            VARCHAR(10) DEFAULT 'PER_100G' NOT NULL,
    ENERGY_KCAL      NUMERIC(7,2),
    ENERGY_KJ        NUMERIC(8,2),
    PROTEIN_G        NUMERIC(6,2),
    CARBS_G          NUMERIC(6,2),
    SUGARS_G         NUMERIC(6,2),
    FAT_G            NUMERIC(6,2),
    SAT_FAT_G        NUMERIC(6,2),
    FIBER_G          NUMERIC(6,2),
    SALT_G           NUMERIC(6,3),
    ALCOHOL_G        NUMERIC(6,2),
    POLYOLS_G        NUMERIC(6,2),
    ENERGY_ORIGIN    VARCHAR(20),
    DATA_QUALITY     VARCHAR(20) NOT NULL,
    METHOD           VARCHAR(20) NOT NULL,
    SAMPLE_COUNT     INTEGER DEFAULT 1 NOT NULL,
    REVIEW_STATUS    VARCHAR(12) DEFAULT 'PENDING' NOT NULL,
    RELEASE_ID       BIGINT,
    SUPERSEDED_BY_ID BIGINT,
    REVIEWED_BY      VARCHAR(255),
    REVIEWED_AT      TIMESTAMPTZ(6),
    NOTES            VARCHAR(1000),
    CREATED_AT       TIMESTAMPTZ(6) DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT PK_NUTRIENT_PROFILES PRIMARY KEY (ID),
    CONSTRAINT FK_NUTRIENT_PROFILES_RELEASE FOREIGN KEY (RELEASE_ID) REFERENCES CATALOG_RELEASES (ID),
    CONSTRAINT FK_NUTRIENT_PROFILES_SUPERSEDED FOREIGN KEY (SUPERSEDED_BY_ID) REFERENCES NUTRIENT_PROFILES (ID),
    CONSTRAINT CK_NUTRIENT_PROFILES_ROLE CHECK (PROFILE_ROLE IN ('SOURCE_OBSERVATION','REPRESENTATIVE','CUSTOM','PRODUCT_LABEL')),
    CONSTRAINT CK_NUTRIENT_PROFILES_BASIS CHECK (BASIS IN ('PER_100G','PER_100ML')),
    CONSTRAINT CK_NUTRIENT_PROFILES_QUALITY CHECK (DATA_QUALITY IN ('VERIFIED','AVERAGE','ESTIMATE','CUSTOM')),
    CONSTRAINT CK_NUTRIENT_PROFILES_METHOD CHECK (METHOD IN ('SINGLE_SOURCE','MEDIAN','WEIGHTED_MEDIAN','LABEL','MANUAL','RECIPE_CALC')),
    CONSTRAINT CK_NUTRIENT_PROFILES_ENERGY_ORIGIN CHECK (ENERGY_ORIGIN IS NULL OR ENERGY_ORIGIN IN ('DECLARED','CALCULATED_EU')),
    CONSTRAINT CK_NUTRIENT_PROFILES_REVIEW CHECK (REVIEW_STATUS IN ('PENDING','APPROVED','REJECTED')),
    CONSTRAINT CK_NUTRIENT_PROFILES_RANGE CHECK (
        COALESCE(ENERGY_KCAL,0) BETWEEN 0 AND 900 AND COALESCE(ENERGY_KJ,0) BETWEEN 0 AND 3800
        AND COALESCE(PROTEIN_G,0) BETWEEN 0 AND 100 AND COALESCE(CARBS_G,0) BETWEEN 0 AND 100
        AND COALESCE(SUGARS_G,0) BETWEEN 0 AND 100 AND COALESCE(FAT_G,0) BETWEEN 0 AND 100
        AND COALESCE(SAT_FAT_G,0) BETWEEN 0 AND 100 AND COALESCE(FIBER_G,0) BETWEEN 0 AND 100
        AND COALESCE(SALT_G,0) BETWEEN 0 AND 100 AND COALESCE(ALCOHOL_G,0) BETWEEN 0 AND 100
        AND COALESCE(POLYOLS_G,0) BETWEEN 0 AND 100),
    CONSTRAINT CK_NUTRIENT_PROFILES_SUBSETS CHECK (
        (SUGARS_G IS NULL OR CARBS_G IS NULL OR SUGARS_G <= CARBS_G + 0.5)
        AND (SAT_FAT_G IS NULL OR FAT_G IS NULL OR SAT_FAT_G <= FAT_G + 0.5)),
    CONSTRAINT CK_NUTRIENT_PROFILES_MASS CHECK (
        BASIS = 'PER_100ML'
        OR COALESCE(PROTEIN_G,0) + COALESCE(CARBS_G,0) + COALESCE(FAT_G,0) + COALESCE(FIBER_G,0) + COALESCE(ALCOHOL_G,0) <= 101)
);
CREATE INDEX IX_NUTRIENT_PROFILES_RELEASE ON NUTRIENT_PROFILES (RELEASE_ID);
CREATE INDEX IX_NUTRIENT_PROFILES_SUPERSEDED ON NUTRIENT_PROFILES (SUPERSEDED_BY_ID);
CREATE INDEX IX_NUTRIENT_PROFILES_REVIEW ON NUTRIENT_PROFILES (REVIEW_STATUS, PROFILE_ROLE);
COMMENT ON TABLE NUTRIENT_PROFILES IS 'Valores por 100 g/100 ml. Restricciones = imposibles físicos; las sospechas (incoherencia kcal-macros, atípicos) las marca el importador para revisión. Un perfil aprobado no se modifica: se sustituye (SUPERSEDED_BY_ID).';
COMMENT ON COLUMN NUTRIENT_PROFILES.CARBS_G IS 'Hidratos de carbono disponibles (criterio UE, sin fibra).';
COMMENT ON COLUMN NUTRIENT_PROFILES.DATA_QUALITY IS 'VERIFIED=dato contrastado; AVERAGE=promedio representativo; ESTIMATE=estimación; CUSTOM=dato personalizado.';
COMMENT ON COLUMN NUTRIENT_PROFILES.ENERGY_ORIGIN IS 'DECLARED: valor de la fuente; CALCULATED_EU: calculado con factores del anexo XIV del Reglamento 1169/2011.';

-- Integridad histórica: los valores de un perfil aprobado no cambian nunca.
CREATE OR REPLACE FUNCTION TRG_NUTRIENT_PROFILES_IMMUTABLE_FN() RETURNS trigger AS $$
BEGIN
    RAISE EXCEPTION 'Un perfil nutricional aprobado es inmutable: cree un perfil nuevo y enlácelo con SUPERSEDED_BY_ID.' USING ERRCODE = '23514';
END $$ LANGUAGE plpgsql;
CREATE TRIGGER TRG_NUTRIENT_PROFILES_IMMUTABLE
BEFORE UPDATE OF BASIS, ENERGY_KCAL, ENERGY_KJ, PROTEIN_G, CARBS_G, SUGARS_G, FAT_G, SAT_FAT_G,
                 FIBER_G, SALT_G, ALCOHOL_G, POLYOLS_G ON NUTRIENT_PROFILES
FOR EACH ROW WHEN (OLD.REVIEW_STATUS = 'APPROVED')
EXECUTE FUNCTION TRG_NUTRIENT_PROFILES_IMMUTABLE_FN();

