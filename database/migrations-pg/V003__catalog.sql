-- Conversión entre variantes (rendimiento de cocción: 100 g de arroz crudo -> X g cocido).
CREATE TABLE VARIANT_CONVERSIONS (
    ID               BIGINT GENERATED BY DEFAULT AS IDENTITY,
    FROM_VARIANT_ID  BIGINT  NOT NULL,
    TO_VARIANT_ID    BIGINT  NOT NULL,
    WEIGHT_FACTOR    NUMERIC(6,3) NOT NULL,
    FACTOR_MIN       NUMERIC(6,3),
    FACTOR_MAX       NUMERIC(6,3),
    SOURCE_ID        BIGINT,
    NOTE             VARCHAR(300),
    CONSTRAINT PK_VARIANT_CONVERSIONS PRIMARY KEY (ID),
    CONSTRAINT UK_VARIANT_CONVERSIONS UNIQUE (FROM_VARIANT_ID, TO_VARIANT_ID),
    CONSTRAINT FK_VARIANT_CONV_FROM FOREIGN KEY (FROM_VARIANT_ID) REFERENCES FOOD_VARIANTS (ID) ON DELETE CASCADE,
    CONSTRAINT FK_VARIANT_CONV_TO FOREIGN KEY (TO_VARIANT_ID) REFERENCES FOOD_VARIANTS (ID) ON DELETE CASCADE,
    CONSTRAINT FK_VARIANT_CONV_SOURCE FOREIGN KEY (SOURCE_ID) REFERENCES DATA_SOURCES (ID),
    CONSTRAINT CK_VARIANT_CONV_FACTOR CHECK (WEIGHT_FACTOR > 0
        AND (FACTOR_MIN IS NULL OR FACTOR_MIN <= WEIGHT_FACTOR)
        AND (FACTOR_MAX IS NULL OR FACTOR_MAX >= WEIGHT_FACTOR)),
    CONSTRAINT CK_VARIANT_CONV_DISTINCT CHECK (FROM_VARIANT_ID <> TO_VARIANT_ID)
);
CREATE INDEX IX_VARIANT_CONV_TO ON VARIANT_CONVERSIONS (TO_VARIANT_ID);
CREATE INDEX IX_VARIANT_CONV_SOURCE ON VARIANT_CONVERSIONS (SOURCE_ID);
COMMENT ON TABLE VARIANT_CONVERSIONS IS 'Peso_destino = peso_origen x WEIGHT_FACTOR. Evita confundir hidratos de 100 g de arroz crudo con 100 g de arroz cocido. FK origen cubierta por UK_VARIANT_CONVERSIONS.';

