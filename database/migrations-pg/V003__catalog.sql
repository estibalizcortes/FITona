-- Registros brutos importados (procedencia trazable). Sus valores van a un NUTRIENT_PROFILE con rol SOURCE_OBSERVATION.
CREATE TABLE SOURCE_RECORDS (
    ID                  BIGINT GENERATED BY DEFAULT AS IDENTITY,
    BATCH_ID            BIGINT         NOT NULL,
    SOURCE_ID           BIGINT         NOT NULL,
    EXTERNAL_ID         VARCHAR(100) NOT NULL,
    RAW_NAME            VARCHAR(400) NOT NULL,
    NORMALIZED_NAME_KEY VARCHAR(400),
    BRAND_NAME          VARCHAR(200),
    BARCODE             VARCHAR(14),
    STATE_GUESS         VARCHAR(20),
    OBSERVED_PROFILE_ID BIGINT,
    RAW_PAYLOAD         JSONB,
    MATCHED_VARIANT_ID  BIGINT,
    MATCH_SCORE         NUMERIC(5,4),
    MATCH_STATUS        VARCHAR(20) DEFAULT 'UNMATCHED' NOT NULL,
    QUALITY_FLAGS       JSONB,
    IMPORTED_AT         TIMESTAMPTZ(6) DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT PK_SOURCE_RECORDS PRIMARY KEY (ID),
    CONSTRAINT UK_SOURCE_RECORDS_EXTERNAL UNIQUE (BATCH_ID, EXTERNAL_ID),
    CONSTRAINT FK_SOURCE_RECORDS_BATCH FOREIGN KEY (BATCH_ID) REFERENCES IMPORT_BATCHES (ID),
    CONSTRAINT FK_SOURCE_RECORDS_SOURCE FOREIGN KEY (SOURCE_ID) REFERENCES DATA_SOURCES (ID),
    CONSTRAINT FK_SOURCE_RECORDS_PROFILE FOREIGN KEY (OBSERVED_PROFILE_ID) REFERENCES NUTRIENT_PROFILES (ID),
    CONSTRAINT FK_SOURCE_RECORDS_VARIANT FOREIGN KEY (MATCHED_VARIANT_ID) REFERENCES FOOD_VARIANTS (ID) ON DELETE SET NULL,
    CONSTRAINT CK_SOURCE_RECORDS_MATCH CHECK (MATCH_STATUS IN
        ('UNMATCHED','AUTO_MATCHED','CONFIRMED','REJECTED','NEW_VARIANT_PROPOSED','IGNORED'))
);
CREATE INDEX IX_SOURCE_RECORDS_SOURCE ON SOURCE_RECORDS (SOURCE_ID, EXTERNAL_ID);
CREATE INDEX IX_SOURCE_RECORDS_PROFILE ON SOURCE_RECORDS (OBSERVED_PROFILE_ID);
CREATE INDEX IX_SOURCE_RECORDS_VARIANT ON SOURCE_RECORDS (MATCHED_VARIANT_ID);
CREATE INDEX IX_SOURCE_RECORDS_STATUS ON SOURCE_RECORDS (MATCH_STATUS);
COMMENT ON TABLE SOURCE_RECORDS IS 'Dato tal como llegó de la fuente + resultado de normalización y emparejamiento. FK de lote cubierta por UK_SOURCE_RECORDS_EXTERNAL.';

-- Qué observaciones forman cada perfil representativo y cuáles se excluyeron (y por qué).
CREATE TABLE PROFILE_CONTRIBUTIONS (
    REPRESENTATIVE_PROFILE_ID BIGINT NOT NULL,
    SOURCE_RECORD_ID          BIGINT NOT NULL,
    WEIGHT                    NUMERIC(5,4) DEFAULT 1 NOT NULL,
    EXCLUDED                  BOOLEAN DEFAULT FALSE NOT NULL,
    EXCLUSION_REASON          VARCHAR(40),
    CONSTRAINT PK_PROFILE_CONTRIBUTIONS PRIMARY KEY (REPRESENTATIVE_PROFILE_ID, SOURCE_RECORD_ID),
    CONSTRAINT FK_PROFILE_CONTRIB_PROFILE FOREIGN KEY (REPRESENTATIVE_PROFILE_ID) REFERENCES NUTRIENT_PROFILES (ID) ON DELETE CASCADE,
    CONSTRAINT FK_PROFILE_CONTRIB_RECORD FOREIGN KEY (SOURCE_RECORD_ID) REFERENCES SOURCE_RECORDS (ID),
    CONSTRAINT CK_PROFILE_CONTRIB_WEIGHT CHECK (WEIGHT BETWEEN 0 AND 1),
