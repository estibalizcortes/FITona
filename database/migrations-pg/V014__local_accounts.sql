-- V014 · Cuentas con correo y contraseña (sustituye la identidad de desarrollo para uso real).
-- La contraseña NUNCA se guarda: solo un hash PBKDF2 con sal. Las sesiones guardan el hash SHA-256 del token, no el token.
-- Borrar APP_USERS elimina en cascada credenciales y sesiones (RGPD: supresión).
CREATE TABLE USER_CREDENTIALS (
    USER_ID        BYTEA            NOT NULL,
    EMAIL_NORM     VARCHAR(254) NOT NULL,
    PASSWORD_HASH  VARCHAR(200) NOT NULL,
    CREATED_AT     TIMESTAMPTZ(6) DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT PK_USER_CREDENTIALS PRIMARY KEY (USER_ID),
    CONSTRAINT UK_USER_CREDENTIALS_EMAIL UNIQUE (EMAIL_NORM),
    CONSTRAINT FK_USER_CREDENTIALS_USER FOREIGN KEY (USER_ID) REFERENCES APP_USERS (ID) ON DELETE CASCADE
);
COMMENT ON TABLE USER_CREDENTIALS IS 'Correo (minúsculas) y hash PBKDF2 de la contraseña. Dato personal: se borra con la cuenta.';

CREATE TABLE AUTH_SESSIONS (
    TOKEN_HASH  VARCHAR(64) NOT NULL,
    USER_ID     BYTEA           NOT NULL,
    CREATED_AT  TIMESTAMPTZ(6) DEFAULT CURRENT_TIMESTAMP NOT NULL,
    EXPIRES_AT  TIMESTAMPTZ(6) NOT NULL,
    CONSTRAINT PK_AUTH_SESSIONS PRIMARY KEY (TOKEN_HASH),
    CONSTRAINT FK_AUTH_SESSIONS_USER FOREIGN KEY (USER_ID) REFERENCES APP_USERS (ID) ON DELETE CASCADE
);
CREATE INDEX IX_AUTH_SESSIONS_USER ON AUTH_SESSIONS (USER_ID);
COMMENT ON TABLE AUTH_SESSIONS IS 'Sesiones abiertas: SHA-256 (hex) del token que tiene el dispositivo. Caducan solas.';
