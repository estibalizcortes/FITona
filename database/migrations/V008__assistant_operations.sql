CREATE TABLE ASSISTANT_MEMORIES (
    ID             RAW(16) DEFAULT SYS_GUID() NOT NULL,
    USER_ID        RAW(16)            NOT NULL,
    CATEGORY       VARCHAR2(20 CHAR)  NOT NULL,
    CONTENT        VARCHAR2(500 CHAR) NOT NULL,
    MEMORY_ORIGIN  VARCHAR2(20 CHAR)  NOT NULL,
    LAST_USED_AT   TIMESTAMP(6) WITH TIME ZONE,
    CREATED_AT     TIMESTAMP(6) WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_ASSISTANT_MEMORIES PRIMARY KEY (ID),
    CONSTRAINT FK_ASSISTANT_MEMORIES_USER FOREIGN KEY (USER_ID) REFERENCES APP_USERS (ID) ON DELETE CASCADE,
    CONSTRAINT CK_ASSISTANT_MEMORIES_CATEGORY CHECK (CATEGORY IN ('PREFERENCE','APPLIANCE','ROUTINE','HOUSEHOLD','COOKING','OTHER')),
    CONSTRAINT CK_ASSISTANT_MEMORIES_ORIGIN CHECK (MEMORY_ORIGIN IN ('USER_STATED','PROPOSED_CONFIRMED'))
);
CREATE INDEX IX_ASSISTANT_MEMORIES_USER ON ASSISTANT_MEMORIES (USER_ID, CATEGORY);
COMMENT ON TABLE ASSISTANT_MEMORIES IS 'Memoria del asistente visible, editable y borrable por la persona. Nunca se guarda nada que no haya confirmado.';

CREATE TABLE AI_ACTION_PROPOSALS (
    ID           RAW(16) DEFAULT SYS_GUID() NOT NULL,
    USER_ID      RAW(16)           NOT NULL,
    ACTION_CODE  VARCHAR2(30 CHAR) NOT NULL,
    PAYLOAD      JSON              NOT NULL,
    PREVIEW      JSON,
    STATUS       VARCHAR2(10 CHAR) DEFAULT 'PROPOSED' NOT NULL,
    CREATED_AT   TIMESTAMP(6) WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    EXPIRES_AT   TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    DECIDED_AT   TIMESTAMP(6) WITH TIME ZONE,
    RESULT_REF   VARCHAR2(100 CHAR),
    CONSTRAINT PK_AI_ACTION_PROPOSALS PRIMARY KEY (ID),
    CONSTRAINT FK_AI_PROPOSALS_USER FOREIGN KEY (USER_ID) REFERENCES APP_USERS (ID) ON DELETE CASCADE,
    CONSTRAINT CK_AI_PROPOSALS_ACTION CHECK (ACTION_CODE IN
        ('LOG_FOOD','REPLACE_PLAN_ITEM','CREATE_PLAN','UPDATE_PLAN','ADD_SHOPPING_ITEMS','UPDATE_PANTRY',
         'CREATE_RECIPE','SET_TARGETS','REMEMBER_FACT','LOG_ACTIVITY')),
    CONSTRAINT CK_AI_PROPOSALS_STATUS CHECK (STATUS IN ('PROPOSED','CONFIRMED','REJECTED','EXPIRED','FAILED')),
    CONSTRAINT CK_AI_PROPOSALS_EXPIRY CHECK (EXPIRES_AT > CREATED_AT)
);
CREATE INDEX IX_AI_PROPOSALS_USER ON AI_ACTION_PROPOSALS (USER_ID, STATUS, CREATED_AT);
CREATE INDEX IX_AI_PROPOSALS_EXPIRY ON AI_ACTION_PROPOSALS (EXPIRES_AT);
COMMENT ON TABLE AI_ACTION_PROPOSALS IS 'Toda acción que la IA quiera ejecutar queda aquí como propuesta validada por el backend y solo se aplica tras confirmación explícita. Purga periódica.';

CREATE TABLE AI_USAGE_EVENTS (
    ID                    NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY,
    USER_ID               RAW(16),
    FEATURE               VARCHAR2(20 CHAR) NOT NULL,
    PROVIDER              VARCHAR2(20 CHAR) NOT NULL,
    MODEL                 VARCHAR2(60 CHAR) NOT NULL,
    INPUT_TOKENS          NUMBER(9) DEFAULT 0 NOT NULL,
    CACHED_INPUT_TOKENS   NUMBER(9) DEFAULT 0 NOT NULL,
    OUTPUT_TOKENS         NUMBER(9) DEFAULT 0 NOT NULL,
    COST_USD_MICROS       NUMBER(12) DEFAULT 0 NOT NULL,
    LATENCY_MS            NUMBER(8),
    OUTCOME               VARCHAR2(16 CHAR) NOT NULL,
    CREATED_AT            TIMESTAMP(6) WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_AI_USAGE_EVENTS PRIMARY KEY (ID),
    CONSTRAINT FK_AI_USAGE_EVENTS_USER FOREIGN KEY (USER_ID) REFERENCES APP_USERS (ID) ON DELETE SET NULL,
    CONSTRAINT CK_AI_USAGE_FEATURE CHECK (FEATURE IN
        ('TEXT_LOG','PHOTO_LOG','CHAT','MENU_GENERATION','RECIPE_SUGGESTION','RECIPE_IMPORT','RECEIPT_OCR','SCREENSHOT_OCR','LABEL_OCR')),
    CONSTRAINT CK_AI_USAGE_OUTCOME CHECK (OUTCOME IN ('OK','ERROR','BLOCKED_QUOTA','BLOCKED_SAFETY','BLOCKED_CONSENT','TIMEOUT')),
    CONSTRAINT CK_AI_USAGE_TOKENS CHECK (INPUT_TOKENS >= 0 AND CACHED_INPUT_TOKENS >= 0 AND OUTPUT_TOKENS >= 0 AND COST_USD_MICROS >= 0)
);
CREATE INDEX IX_AI_USAGE_USER ON AI_USAGE_EVENTS (USER_ID, CREATED_AT);
CREATE INDEX IX_AI_USAGE_TIME ON AI_USAGE_EVENTS (CREATED_AT, FEATURE);
COMMENT ON TABLE AI_USAGE_EVENTS IS 'Medición de consumo y coste por función, SIN contenido de las peticiones. Base de cuotas por persona y del límite global de gasto.';

CREATE TABLE USER_ENTITLEMENTS (
    ID             RAW(16) DEFAULT SYS_GUID() NOT NULL,
    USER_ID        RAW(16)           NOT NULL,
    PLAN_CODE      VARCHAR2(20 CHAR) NOT NULL,
    GRANT_SOURCE   VARCHAR2(12 CHAR) NOT NULL,
    VALID_FROM     TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    VALID_TO       TIMESTAMP(6) WITH TIME ZONE,
    EXTERNAL_REF   VARCHAR2(200 CHAR),
    CREATED_AT     TIMESTAMP(6) WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_USER_ENTITLEMENTS PRIMARY KEY (ID),
    CONSTRAINT FK_USER_ENTITLEMENTS_USER FOREIGN KEY (USER_ID) REFERENCES APP_USERS (ID) ON DELETE CASCADE,
    CONSTRAINT CK_USER_ENTITLEMENTS_PLAN CHECK (PLAN_CODE IN ('FREE','PLUS','BETA_TESTER')),
    CONSTRAINT CK_USER_ENTITLEMENTS_SOURCE CHECK (GRANT_SOURCE IN ('DEFAULT','MANUAL','APP_STORE','PLAY_STORE','WEB')),
    CONSTRAINT CK_USER_ENTITLEMENTS_DATES CHECK (VALID_TO IS NULL OR VALID_TO > VALID_FROM)
);
CREATE INDEX IX_USER_ENTITLEMENTS_USER ON USER_ENTITLEMENTS (USER_ID, VALID_FROM);
COMMENT ON TABLE USER_ENTITLEMENTS IS 'Derecho de uso (gratuito / Plus). Preparado para pagos futuros; en v0.x solo se asigna manualmente.';

CREATE TABLE IDEMPOTENCY_KEYS (
    USER_ID          RAW(16)           NOT NULL,
    IDEMPOTENCY_KEY  VARCHAR2(64 CHAR) NOT NULL,
    REQUEST_HASH     VARCHAR2(64 CHAR) NOT NULL,
    RESPONSE_STATUS  NUMBER(3)         NOT NULL,
    RESPONSE_BODY    JSON,
    CREATED_AT       TIMESTAMP(6) WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_IDEMPOTENCY_KEYS PRIMARY KEY (USER_ID, IDEMPOTENCY_KEY),
    CONSTRAINT FK_IDEMPOTENCY_KEYS_USER FOREIGN KEY (USER_ID) REFERENCES APP_USERS (ID) ON DELETE CASCADE
);
CREATE INDEX IX_IDEMPOTENCY_KEYS_CREATED ON IDEMPOTENCY_KEYS (CREATED_AT);
COMMENT ON TABLE IDEMPOTENCY_KEYS IS 'Reintentos seguros desde la cola sin conexión: la misma clave devuelve la misma respuesta. Purga a los 7 días. FK cubierta por la PK.';

CREATE TABLE USER_DATA_REQUESTS (
    ID              RAW(16) DEFAULT SYS_GUID() NOT NULL,
    USER_ID         RAW(16),
    SUBJECT_HASH    VARCHAR2(64 CHAR) NOT NULL,
    REQUEST_KIND    VARCHAR2(10 CHAR) NOT NULL,
    STATUS          VARCHAR2(12 CHAR) DEFAULT 'PENDING' NOT NULL,
    REQUESTED_AT    TIMESTAMP(6) WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    COMPLETED_AT    TIMESTAMP(6) WITH TIME ZONE,
    ARTIFACT_KEY    VARCHAR2(300 CHAR),
    ARTIFACT_EXPIRES_AT TIMESTAMP(6) WITH TIME ZONE,
    CONSTRAINT PK_USER_DATA_REQUESTS PRIMARY KEY (ID),
    CONSTRAINT FK_USER_DATA_REQUESTS_USER FOREIGN KEY (USER_ID) REFERENCES APP_USERS (ID) ON DELETE SET NULL,
    CONSTRAINT CK_USER_DATA_REQUESTS_KIND CHECK (REQUEST_KIND IN ('EXPORT','DELETION')),
    CONSTRAINT CK_USER_DATA_REQUESTS_STATUS CHECK (STATUS IN ('PENDING','RUNNING','COMPLETED','FAILED','CANCELLED'))
);
CREATE INDEX IX_USER_DATA_REQUESTS_USER ON USER_DATA_REQUESTS (USER_ID);
CREATE INDEX IX_USER_DATA_REQUESTS_STATUS ON USER_DATA_REQUESTS (STATUS, REQUESTED_AT);
COMMENT ON TABLE USER_DATA_REQUESTS IS 'Exportación (portabilidad) y supresión de cuenta. Tras borrar la cuenta solo queda SUBJECT_HASH como evidencia de cumplimiento.';

CREATE TABLE AUDIT_EVENTS (
    ID              NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY,
    OCCURRED_AT     TIMESTAMP(6) WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    ACTOR_KIND      VARCHAR2(10 CHAR)  NOT NULL,
    ACTOR_REF       VARCHAR2(255 CHAR),
    ACTION          VARCHAR2(60 CHAR)  NOT NULL,
    TARGET_KIND     VARCHAR2(40 CHAR),
    TARGET_REF      VARCHAR2(100 CHAR),
    OUTCOME         VARCHAR2(10 CHAR)  NOT NULL,
    DETAILS         JSON,
    CONSTRAINT PK_AUDIT_EVENTS PRIMARY KEY (ID),
    CONSTRAINT CK_AUDIT_EVENTS_ACTOR CHECK (ACTOR_KIND IN ('USER','ADMIN','SYSTEM')),
    CONSTRAINT CK_AUDIT_EVENTS_OUTCOME CHECK (OUTCOME IN ('SUCCESS','DENIED','FAILED'))
);
CREATE INDEX IX_AUDIT_EVENTS_TIME ON AUDIT_EVENTS (OCCURRED_AT);
CREATE INDEX IX_AUDIT_EVENTS_TARGET ON AUDIT_EVENTS (TARGET_KIND, TARGET_REF);
COMMENT ON TABLE AUDIT_EVENTS IS 'Auditoría de acciones administrativas y de seguridad (accesos denegados, cambios de catálogo, exportaciones). DETAILS nunca incluye contenido del diario.';

CREATE TABLE APP_SETTINGS (
    SETTING_KEY   VARCHAR2(80 CHAR) NOT NULL,
    SETTING_VALUE JSON              NOT NULL,
    DESCRIPTION   VARCHAR2(500 CHAR),
    UPDATED_AT    TIMESTAMP(6) WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    UPDATED_BY    VARCHAR2(255 CHAR),
    CONSTRAINT PK_APP_SETTINGS PRIMARY KEY (SETTING_KEY)
);
COMMENT ON TABLE APP_SETTINGS IS 'Configuración global editable desde el panel (cuotas de IA, límite de gasto, interruptores de funciones).';
