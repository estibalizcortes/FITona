CREATE INDEX IX_PLANNED_OPTIONS_RECIPE ON PLANNED_MEAL_OPTIONS (RECIPE_VERSION_ID);
CREATE INDEX IX_PLANNED_OPTIONS_BATCH ON PLANNED_MEAL_OPTIONS (PREPARED_BATCH_ID);
COMMENT ON TABLE PLANNED_MEAL_OPTIONS IS 'Opción de comida: una receta, raciones de un lote o una combinación de alimentos (PLANNED_OPTION_ITEMS). FK al hueco cubierta por UK_PLANNED_MEAL_OPTIONS_RANK.';

