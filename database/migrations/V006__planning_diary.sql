    CONSTRAINT CK_PLANNED_MEALS_SLOT CHECK (MEAL_SLOT IN ('BREAKFAST','MID_MORNING','LUNCH','AFTERNOON_SNACK','DINNER','OTHER')),
    CONSTRAINT CK_PLANNED_MEALS_STATUS CHECK (STATUS IN ('PLANNED','DONE','REPLACED','SKIPPED')),
