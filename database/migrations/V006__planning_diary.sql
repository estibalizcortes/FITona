-- Señales de preferencia para no insistir con lo rechazado ("No me apetece", "Repite lo que me gusta").
CREATE TABLE FOOD_FEEDBACK (
    ID             RAW(16) DEFAULT SYS_GUID() NOT NULL,
    USER_ID        RAW(16)           NOT NULL,
    FOOD_ID        NUMBER(10),
    RECIPE_ID      RAW(16),
    FEEDBACK       VARCHAR2(20 CHAR) NOT NULL,
    CONTEXT        VARCHAR2(20 CHAR) NOT NULL,
    EXPIRES_AT     TIMESTAMP(6) WITH TIME ZONE,
    CREATED_AT     TIMESTAMP(6) WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_FOOD_FEEDBACK PRIMARY KEY (ID),
    CONSTRAINT FK_FOOD_FEEDBACK_USER FOREIGN KEY (USER_ID) REFERENCES APP_USERS (ID) ON DELETE CASCADE,
    CONSTRAINT FK_FOOD_FEEDBACK_FOOD FOREIGN KEY (FOOD_ID) REFERENCES FOODS (ID) ON DELETE CASCADE,
    CONSTRAINT FK_FOOD_FEEDBACK_RECIPE FOREIGN KEY (RECIPE_ID) REFERENCES RECIPES (ID) ON DELETE CASCADE,
    CONSTRAINT CK_FOOD_FEEDBACK_TARGET CHECK (
        (FOOD_ID IS NULL AND RECIPE_ID IS NOT NULL) OR (FOOD_ID IS NOT NULL AND RECIPE_ID IS NULL)),
    CONSTRAINT CK_FOOD_FEEDBACK_KIND CHECK (FEEDBACK IN ('REJECTED_SUGGESTION','NOT_IN_MOOD','DISLIKE','LIKE')),
    CONSTRAINT CK_FOOD_FEEDBACK_CONTEXT CHECK (CONTEXT IN ('SUBSTITUTION','PLAN','ASSISTANT','RECIPE'))
);
CREATE INDEX IX_FOOD_FEEDBACK_USER ON FOOD_FEEDBACK (USER_ID, CREATED_AT);
CREATE INDEX IX_FOOD_FEEDBACK_FOOD ON FOOD_FEEDBACK (FOOD_ID);
CREATE INDEX IX_FOOD_FEEDBACK_RECIPE ON FOOD_FEEDBACK (RECIPE_ID);
COMMENT ON TABLE FOOD_FEEDBACK IS 'Señales explícitas. NOT_IN_MOOD caduca (EXPIRES_AT): "hoy no" no significa "nunca".';
