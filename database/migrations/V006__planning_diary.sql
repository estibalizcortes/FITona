CREATE INDEX IX_PLANNED_MEALS_SYNC ON PLANNED_MEALS (MEAL_PLAN_ID, SYNC_SEQ);
CREATE INDEX IX_PLANNED_MEALS_FOR_USER ON PLANNED_MEALS (FOR_USER_ID);
CREATE INDEX IX_PLANNED_MEALS_SELECTED ON PLANNED_MEALS (SELECTED_OPTION_ID);
COMMENT ON TABLE PLANNED_MEALS IS 'Hueco del plan (día + franja). Raíz de agregado para sincronizar sus opciones. FOR_USER_ID nulo = para todo el hogar.';
COMMENT ON COLUMN PLANNED_MEALS.STATUS IS 'REPLACED = se comió otra cosa (el diario lo refleja). SKIPPED = no aplica. Ninguno es un error ni genera compensación.';

-- "Plan alternativo": varias opciones intercambiables para un mismo hueco.
CREATE TABLE PLANNED_MEAL_OPTIONS (
    ID                  RAW(16) DEFAULT SYS_GUID() NOT NULL,
    PLANNED_MEAL_ID     RAW(16)            NOT NULL,
    OPTION_RANK         NUMBER(2) DEFAULT 1 NOT NULL,
    TITLE               VARCHAR2(200 CHAR) NOT NULL,
    RECIPE_VERSION_ID   RAW(16),
    PREPARED_BATCH_ID   RAW(16),
    SERVINGS            NUMBER(6,2) DEFAULT 1 NOT NULL,
    CONSTRAINT PK_PLANNED_MEAL_OPTIONS PRIMARY KEY (ID),
    CONSTRAINT UK_PLANNED_MEAL_OPTIONS_RANK UNIQUE (PLANNED_MEAL_ID, OPTION_RANK),
    CONSTRAINT FK_PLANNED_OPTIONS_MEAL FOREIGN KEY (PLANNED_MEAL_ID) REFERENCES PLANNED_MEALS (ID) ON DELETE CASCADE,
    CONSTRAINT FK_PLANNED_OPTIONS_RECIPE FOREIGN KEY (RECIPE_VERSION_ID) REFERENCES RECIPE_VERSIONS (ID) ON DELETE SET NULL,
    CONSTRAINT FK_PLANNED_OPTIONS_BATCH FOREIGN KEY (PREPARED_BATCH_ID) REFERENCES PREPARED_BATCHES (ID) ON DELETE SET NULL,
    CONSTRAINT CK_PLANNED_OPTIONS_RANK CHECK (OPTION_RANK BETWEEN 1 AND 9),
    CONSTRAINT CK_PLANNED_OPTIONS_SERVINGS CHECK (SERVINGS > 0)
