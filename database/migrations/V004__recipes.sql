-- =============================================================================
-- FITona · V004 · Recetas (propias, familiares, curadas o sugeridas por IA)
-- Cada edición publicada crea una versión inmutable: los registros y planes que
-- usaron una versión anterior siguen siendo coherentes.
-- =============================================================================

CREATE TABLE RECIPES (
    ID                  RAW(16) DEFAULT SYS_GUID() NOT NULL,
    OWNER_USER_ID       RAW(16),
    CURRENT_VERSION_ID  RAW(16),
    ORIGIN              VARCHAR2(20 CHAR) NOT NULL,
    VISIBILITY          VARCHAR2(10 CHAR) DEFAULT 'PRIVATE' NOT NULL,
    SOURCE_URL          VARCHAR2(1000 CHAR),
    SOURCE_ATTRIBUTION  VARCHAR2(300 CHAR),
    STATUS              VARCHAR2(12 CHAR) DEFAULT 'ACTIVE' NOT NULL,
    ROW_VERSION         NUMBER(10) DEFAULT 0 NOT NULL,
    CREATED_AT          TIMESTAMP(6) WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    UPDATED_AT          TIMESTAMP(6) WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    DELETED_AT          TIMESTAMP(6) WITH TIME ZONE,
    SYNC_SEQ            NUMBER(19) NOT NULL,
    CONSTRAINT PK_RECIPES PRIMARY KEY (ID),
    CONSTRAINT FK_RECIPES_OWNER FOREIGN KEY (OWNER_USER_ID) REFERENCES APP_USERS (ID) ON DELETE CASCADE,
    CONSTRAINT CK_RECIPES_ORIGIN CHECK (ORIGIN IN
        ('USER','FAMILY','CURATED','AI_SUGGESTED','IMPORTED_URL','IMPORTED_TEXT','IMPORTED_PHOTO')),
    CONSTRAINT CK_RECIPES_VISIBILITY CHECK (VISIBILITY IN ('PRIVATE','SHARED','CATALOG')),
    CONSTRAINT CK_RECIPES_OWNERSHIP CHECK (
        (OWNER_USER_ID IS NULL AND VISIBILITY = 'CATALOG') OR (OWNER_USER_ID IS NOT NULL AND VISIBILITY <> 'CATALOG')),
    CONSTRAINT CK_RECIPES_STATUS CHECK (STATUS IN ('ACTIVE','ARCHIVED'))
);
CREATE INDEX IX_RECIPES_OWNER ON RECIPES (OWNER_USER_ID, SYNC_SEQ);
CREATE INDEX IX_RECIPES_CURRENT_VERSION ON RECIPES (CURRENT_VERSION_ID);
COMMENT ON TABLE RECIPES IS 'Identidad de una receta. OWNER_USER_ID nulo = receta curada del catálogo. Las importadas guardan URL y atribución; no se copia contenido protegido sin derechos.';

CREATE TABLE RECIPE_VERSIONS (
    ID                      RAW(16) DEFAULT SYS_GUID() NOT NULL,
    RECIPE_ID               RAW(16)            NOT NULL,
    VERSION_NUMBER          NUMBER(5)          NOT NULL,
    TITLE                   VARCHAR2(200 CHAR) NOT NULL,
    DESCRIPTION             VARCHAR2(2000 CHAR),
    SERVINGS                NUMBER(6,2)        NOT NULL,
    COOKED_WEIGHT_G         NUMBER(9,2),
    PREP_MINUTES            NUMBER(4),
    COOK_MINUTES            NUMBER(4),
    ACTIVE_MINUTES          NUMBER(4),
    DIFFICULTY              VARCHAR2(10 CHAR),
    STORAGE_NOTES           VARCHAR2(1000 CHAR),
    FRIDGE_DAYS_MAX         NUMBER(3),
    FREEZER_SUITABLE        BOOLEAN,
    STORAGE_SOURCE_ID       NUMBER(10),
    PHOTO_OBJECT_KEY        VARCHAR2(300 CHAR),
    NUTRITION_COMPLETENESS  VARCHAR2(10 CHAR) DEFAULT 'NONE' NOT NULL,
    SERVING_ENERGY_KCAL     NUMBER(8,2),
    SERVING_PROTEIN_G       NUMBER(7,2),
    SERVING_CARBS_G         NUMBER(7,2),
    SERVING_FAT_G           NUMBER(7,2),
    SERVING_FIBER_G         NUMBER(7,2),
    NUTRITION_COMPUTED_AT   TIMESTAMP(6) WITH TIME ZONE,
    CATALOG_RELEASE_ID      NUMBER(10),
    CREATED_BY_USER_ID      RAW(16),
    CREATED_AT              TIMESTAMP(6) WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_RECIPE_VERSIONS PRIMARY KEY (ID),
    CONSTRAINT UK_RECIPE_VERSIONS_NUMBER UNIQUE (RECIPE_ID, VERSION_NUMBER),
    CONSTRAINT FK_RECIPE_VERSIONS_RECIPE FOREIGN KEY (RECIPE_ID) REFERENCES RECIPES (ID) ON DELETE CASCADE,
    CONSTRAINT FK_RECIPE_VERSIONS_STORAGE_SRC FOREIGN KEY (STORAGE_SOURCE_ID) REFERENCES DATA_SOURCES (ID),
    CONSTRAINT FK_RECIPE_VERSIONS_RELEASE FOREIGN KEY (CATALOG_RELEASE_ID) REFERENCES CATALOG_RELEASES (ID),
    CONSTRAINT FK_RECIPE_VERSIONS_CREATOR FOREIGN KEY (CREATED_BY_USER_ID) REFERENCES APP_USERS (ID) ON DELETE SET NULL,
    CONSTRAINT CK_RECIPE_VERSIONS_SERVINGS CHECK (SERVINGS > 0 AND SERVINGS <= 200),
    CONSTRAINT CK_RECIPE_VERSIONS_MINUTES CHECK (NVL(PREP_MINUTES,0) >= 0 AND NVL(COOK_MINUTES,0) >= 0 AND NVL(ACTIVE_MINUTES,0) >= 0),
    CONSTRAINT CK_RECIPE_VERSIONS_DIFFICULTY CHECK (DIFFICULTY IS NULL OR DIFFICULTY IN ('EASY','MEDIUM','HARD')),
    CONSTRAINT CK_RECIPE_VERSIONS_COMPLETENESS CHECK (NUTRITION_COMPLETENESS IN ('COMPLETE','PARTIAL','NONE')),
    CONSTRAINT CK_RECIPE_VERSIONS_FRIDGE CHECK (FRIDGE_DAYS_MAX IS NULL OR (FRIDGE_DAYS_MAX BETWEEN 0 AND 30 AND STORAGE_SOURCE_ID IS NOT NULL))
);
CREATE INDEX IX_RECIPE_VERSIONS_STORAGE_SRC ON RECIPE_VERSIONS (STORAGE_SOURCE_ID);
CREATE INDEX IX_RECIPE_VERSIONS_RELEASE ON RECIPE_VERSIONS (CATALOG_RELEASE_ID);
CREATE INDEX IX_RECIPE_VERSIONS_CREATOR ON RECIPE_VERSIONS (CREATED_BY_USER_ID);
COMMENT ON TABLE RECIPE_VERSIONS IS 'Versión inmutable. La nutrición por ración la calcula el motor determinista (nunca la IA) y se guarda con la versión de catálogo usada. FK de receta cubierta por UK_RECIPE_VERSIONS_NUMBER.';
COMMENT ON COLUMN RECIPE_VERSIONS.FRIDGE_DAYS_MAX IS 'Solo se rellena con una fuente de seguridad alimentaria identificada (STORAGE_SOURCE_ID). La IA no puede inventarlo.';

ALTER TABLE RECIPES ADD CONSTRAINT FK_RECIPES_CURRENT_VERSION
    FOREIGN KEY (CURRENT_VERSION_ID) REFERENCES RECIPE_VERSIONS (ID) ON DELETE SET NULL;

CREATE TABLE RECIPE_INGREDIENTS (
    ID                 RAW(16) DEFAULT SYS_GUID() NOT NULL,
    RECIPE_VERSION_ID  RAW(16)    NOT NULL,
    SORT_ORDER         NUMBER(4)  NOT NULL,
    GROUP_LABEL        VARCHAR2(80 CHAR),
    VARIANT_ID         NUMBER(10),
    PRODUCT_ID         NUMBER(19),
    FREE_TEXT          VARCHAR2(200 CHAR),
    QUANTITY           NUMBER(10,3),
    UNIT_CODE          VARCHAR2(20 CHAR),
    GRAMS              NUMBER(9,2),
    IS_OPTIONAL        BOOLEAN DEFAULT FALSE NOT NULL,
    IS_TO_TASTE        BOOLEAN DEFAULT FALSE NOT NULL,
    NOTE               VARCHAR2(300 CHAR),
    CONSTRAINT PK_RECIPE_INGREDIENTS PRIMARY KEY (ID),
    CONSTRAINT FK_RECIPE_INGR_VERSION FOREIGN KEY (RECIPE_VERSION_ID) REFERENCES RECIPE_VERSIONS (ID) ON DELETE CASCADE,
    CONSTRAINT FK_RECIPE_INGR_VARIANT FOREIGN KEY (VARIANT_ID) REFERENCES FOOD_VARIANTS (ID) ON DELETE SET NULL,
    CONSTRAINT FK_RECIPE_INGR_PRODUCT FOREIGN KEY (PRODUCT_ID) REFERENCES COMMERCIAL_PRODUCTS (ID) ON DELETE SET NULL,
    CONSTRAINT FK_RECIPE_INGR_UNIT FOREIGN KEY (UNIT_CODE) REFERENCES PORTION_UNITS (CODE),
    CONSTRAINT CK_RECIPE_INGR_REFERENCE CHECK (VARIANT_ID IS NOT NULL OR PRODUCT_ID IS NOT NULL OR FREE_TEXT IS NOT NULL),
    CONSTRAINT CK_RECIPE_INGR_QUANTITY CHECK (NVL(QUANTITY,0) >= 0 AND NVL(GRAMS,0) >= 0)
);
CREATE INDEX IX_RECIPE_INGR_VERSION ON RECIPE_INGREDIENTS (RECIPE_VERSION_ID, SORT_ORDER);
CREATE INDEX IX_RECIPE_INGR_VARIANT ON RECIPE_INGREDIENTS (VARIANT_ID);
CREATE INDEX IX_RECIPE_INGR_PRODUCT ON RECIPE_INGREDIENTS (PRODUCT_ID);
CREATE INDEX IX_RECIPE_INGR_UNIT ON RECIPE_INGREDIENTS (UNIT_CODE);
COMMENT ON TABLE RECIPE_INGREDIENTS IS 'Ingredientes. FREE_TEXT sin resolver se admite (receta familiar aproximada): la nutrición queda PARTIAL y se indica.';

CREATE TABLE RECIPE_STEPS (
    RECIPE_VERSION_ID  RAW(16)    NOT NULL,
    STEP_NUMBER        NUMBER(3)  NOT NULL,
    INSTRUCTION        VARCHAR2(2000 CHAR) NOT NULL,
    DURATION_MINUTES   NUMBER(4),
    TEMPERATURE_C      NUMBER(4),
    SAFETY_NOTE        VARCHAR2(500 CHAR),
    CONSTRAINT PK_RECIPE_STEPS PRIMARY KEY (RECIPE_VERSION_ID, STEP_NUMBER),
    CONSTRAINT FK_RECIPE_STEPS_VERSION FOREIGN KEY (RECIPE_VERSION_ID) REFERENCES RECIPE_VERSIONS (ID) ON DELETE CASCADE,
    CONSTRAINT CK_RECIPE_STEPS_TEMP CHECK (TEMPERATURE_C IS NULL OR TEMPERATURE_C BETWEEN -40 AND 300)
);
COMMENT ON TABLE RECIPE_STEPS IS 'Pasos de preparación. FK cubierta por la PK.';

CREATE TABLE RECIPE_TAGS (
    RECIPE_VERSION_ID  RAW(16)           NOT NULL,
    TAG_CODE           VARCHAR2(40 CHAR) NOT NULL,
    CONSTRAINT PK_RECIPE_TAGS PRIMARY KEY (RECIPE_VERSION_ID, TAG_CODE),
    CONSTRAINT FK_RECIPE_TAGS_VERSION FOREIGN KEY (RECIPE_VERSION_ID) REFERENCES RECIPE_VERSIONS (ID) ON DELETE CASCADE,
    CONSTRAINT FK_RECIPE_TAGS_TAG FOREIGN KEY (TAG_CODE) REFERENCES TAG_DEFINITIONS (CODE)
);
CREATE INDEX IX_RECIPE_TAGS_TAG ON RECIPE_TAGS (TAG_CODE);
COMMENT ON TABLE RECIPE_TAGS IS 'Etiquetas para filtros (5 ingredientes, airfryer, táper, sobras...).';

CREATE TABLE RECIPE_SHARES (
    ID                   RAW(16) DEFAULT SYS_GUID() NOT NULL,
    RECIPE_ID            RAW(16)           NOT NULL,
    SHARED_WITH_USER_ID  RAW(16),
    HOUSEHOLD_ID         RAW(16),
    PERMISSION           VARCHAR2(10 CHAR) DEFAULT 'VIEW' NOT NULL,
    GRANTED_BY_USER_ID   RAW(16)           NOT NULL,
    GRANTED_AT           TIMESTAMP(6) WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    REVOKED_AT           TIMESTAMP(6) WITH TIME ZONE,
    CONSTRAINT PK_RECIPE_SHARES PRIMARY KEY (ID),
    CONSTRAINT FK_RECIPE_SHARES_RECIPE FOREIGN KEY (RECIPE_ID) REFERENCES RECIPES (ID) ON DELETE CASCADE,
    CONSTRAINT FK_RECIPE_SHARES_USER FOREIGN KEY (SHARED_WITH_USER_ID) REFERENCES APP_USERS (ID) ON DELETE CASCADE,
    CONSTRAINT FK_RECIPE_SHARES_HOUSEHOLD FOREIGN KEY (HOUSEHOLD_ID) REFERENCES HOUSEHOLDS (ID) ON DELETE CASCADE,
    CONSTRAINT FK_RECIPE_SHARES_GRANTOR FOREIGN KEY (GRANTED_BY_USER_ID) REFERENCES APP_USERS (ID) ON DELETE CASCADE,
    CONSTRAINT CK_RECIPE_SHARES_TARGET CHECK (
        (SHARED_WITH_USER_ID IS NULL AND HOUSEHOLD_ID IS NOT NULL) OR (SHARED_WITH_USER_ID IS NOT NULL AND HOUSEHOLD_ID IS NULL)),
    CONSTRAINT CK_RECIPE_SHARES_PERMISSION CHECK (PERMISSION IN ('VIEW','EDIT'))
);
CREATE INDEX IX_RECIPE_SHARES_RECIPE ON RECIPE_SHARES (RECIPE_ID);
CREATE INDEX IX_RECIPE_SHARES_USER ON RECIPE_SHARES (SHARED_WITH_USER_ID);
CREATE INDEX IX_RECIPE_SHARES_HOUSEHOLD ON RECIPE_SHARES (HOUSEHOLD_ID);
CREATE INDEX IX_RECIPE_SHARES_GRANTOR ON RECIPE_SHARES (GRANTED_BY_USER_ID);
COMMENT ON TABLE RECIPE_SHARES IS 'Compartir recetas con una persona o un hogar mediante permiso explícito y revocable.';

CREATE TABLE RECIPE_USER_STATES (
    USER_ID          RAW(16) NOT NULL,
    RECIPE_ID        RAW(16) NOT NULL,
    IS_FAVORITE      BOOLEAN DEFAULT FALSE NOT NULL,
    TIMES_COOKED     NUMBER(6) DEFAULT 0 NOT NULL,
    LAST_COOKED_ON   DATE,
    FEEDBACK         VARCHAR2(10 CHAR),
    UPDATED_AT       TIMESTAMP(6) WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_RECIPE_USER_STATES PRIMARY KEY (USER_ID, RECIPE_ID),
    CONSTRAINT FK_RECIPE_USER_STATES_USER FOREIGN KEY (USER_ID) REFERENCES APP_USERS (ID) ON DELETE CASCADE,
    CONSTRAINT FK_RECIPE_USER_STATES_RECIPE FOREIGN KEY (RECIPE_ID) REFERENCES RECIPES (ID) ON DELETE CASCADE,
    CONSTRAINT CK_RECIPE_USER_STATES_FEEDBACK CHECK (FEEDBACK IS NULL OR FEEDBACK IN ('LOVE','OK','DISLIKE'))
);
CREATE INDEX IX_RECIPE_USER_STATES_RECIPE ON RECIPE_USER_STATES (RECIPE_ID);
COMMENT ON TABLE RECIPE_USER_STATES IS 'Favoritos, veces cocinada y valoración personal (alimenta "Repite lo que me gusta").';
