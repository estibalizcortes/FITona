#!/usr/bin/env python3
"""Convierte las migraciones DDL de Oracle (database/migrations/V001-V009, V014...) a PostgreSQL (database/migrations-pg).
Solo cubre las construcciones que usa este proyecto; si falla en PostgreSQL al aplicar, se corrige aquí.
Las semillas PL/SQL (V010-V013) NO pasan por aquí: se regeneran con sus scripts de database/seed (opción --pg).
Uso: python3 database/tools/oracle_to_pg.py
"""
import pathlib, re

ROOT = pathlib.Path(__file__).resolve().parents[1]
SRC, DST = ROOT / "migrations", ROOT / "migrations-pg"
SKIP = re.compile(r"^(V01[0-3]_|R__)")  # semillas PL/SQL y permisos: versión PG propia

SYNC_FN = """CREATE OR REPLACE FUNCTION TRG_SYNC() RETURNS trigger AS $$
BEGIN
    NEW.SYNC_SEQ := nextval('SYNC_SEQ_GEN');
    IF TG_OP = 'UPDATE' THEN NEW.UPDATED_AT := CURRENT_TIMESTAMP; END IF;
    RETURN NEW;
END $$ LANGUAGE plpgsql;
"""


def convert(sql: str) -> str:
    # Disparadores: solo hay dos patrones (sincronización y perfil inmutable).
    def trig(m):
        name, table = m.group(1), m.group(2)
        return f"CREATE TRIGGER {name} BEFORE INSERT OR UPDATE ON {table} FOR EACH ROW EXECUTE FUNCTION TRG_SYNC();\n"
    sql = re.sub(r"CREATE OR REPLACE TRIGGER (\w+) BEFORE INSERT OR UPDATE ON (\w+) FOR EACH ROW\nBEGIN\n.*?\nEND;\n/\n",
                 trig, sql, flags=re.S)
    sql = re.sub(r"CREATE OR REPLACE TRIGGER TRG_NUTRIENT_PROFILES_IMMUTABLE\n(BEFORE UPDATE OF [^\n]*\n[^\n]*?)\nFOR EACH ROW\nWHEN \(OLD\.REVIEW_STATUS = 'APPROVED'\)\nBEGIN\n.*?\nEND;\n/\n",
                 lambda m: ("CREATE OR REPLACE FUNCTION TRG_NUTRIENT_PROFILES_IMMUTABLE_FN() RETURNS trigger AS $$\nBEGIN\n"
                            "    RAISE EXCEPTION 'Un perfil nutricional aprobado es inmutable: cree un perfil nuevo y enlácelo con SUPERSEDED_BY_ID.' USING ERRCODE = '23514';\n"
                            "END $$ LANGUAGE plpgsql;\n"
                            f"CREATE TRIGGER TRG_NUTRIENT_PROFILES_IMMUTABLE\n{m.group(1)}\nFOR EACH ROW WHEN (OLD.REVIEW_STATUS = 'APPROVED')\nEXECUTE FUNCTION TRG_NUTRIENT_PROFILES_IMMUTABLE_FN();\n"),
                 sql, flags=re.S)
    if "EXECUTE FUNCTION TRG_SYNC()" in sql:
        sql = SYNC_FN + sql
    sql = re.sub(r"VARCHAR2\((\d+)\s*(?:CHAR|BYTE)?\)", r"VARCHAR(\1)", sql)
    sql = sql.replace("RAW(16)", "BYTEA").replace("BLOB", "BYTEA").replace("CLOB", "TEXT")
    sql = re.sub(r"NUMBER\((\d+),\s*(\d+)\)", r"NUMERIC(\1,\2)", sql)
    sql = re.sub(r"NUMBER\((\d+)\)", lambda m: "BIGINT" if int(m.group(1)) >= 10 else "INTEGER", sql)
    sql = re.sub(r"\bNUMBER\b(?!\w)(?=[ ,\n])", "NUMERIC", sql)
    sql = sql.replace("TIMESTAMP(6) WITH TIME ZONE", "TIMESTAMPTZ(6)").replace("SYSTIMESTAMP", "CURRENT_TIMESTAMP")
    sql = sql.replace("GENERATED BY DEFAULT ON NULL AS IDENTITY", "GENERATED BY DEFAULT AS IDENTITY")
    sql = sql.replace("DEFAULT SYS_GUID()", "DEFAULT decode(replace(gen_random_uuid()::text, '-', ''), 'hex')")
    sql = re.sub(r"(?m)^(\s+\w+\s+)JSON\b", r"\1JSONB", sql)
    sql = sql.replace("NVL(", "COALESCE(").replace(" NOCYCLE", " NO CYCLE")
    # PostgreSQL exige paréntesis extra en los índices sobre expresiones.
    sql = re.sub(r"(CREATE (?:UNIQUE )?INDEX [^;]*?;)",
                 lambda m: re.sub(r"CASE WHEN .*? END", lambda c: "(" + c.group(0) + ")", m.group(1), flags=re.S), sql, flags=re.S)
    return sql


def main():
    DST.mkdir(exist_ok=True)
    for f in sorted(SRC.glob("V*.sql")):
        if SKIP.match(f.name):
            continue
        (DST / f.name).write_text(convert(f.read_text(encoding="utf-8")), encoding="utf-8")
        print("convertida", f.name)


if __name__ == "__main__":
    main()
